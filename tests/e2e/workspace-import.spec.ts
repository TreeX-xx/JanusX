import { expect, test } from '@playwright/test'

test('Local picker cancel keeps the dialog; selection imports and restores focus', async ({ page }) => {
  await page.goto('/workspace-import.html')
  const trigger = page.getByRole('button', { name: 'Add workspace', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Add workspace' })
  await page.evaluate(() => { (window as any).workspaceImportFixture.cancelLocal = true })
  await dialog.getByRole('button', { name: 'Choose folder' }).click()
  await expect(dialog).toBeVisible()
  await page.evaluate(() => { (window as any).workspaceImportFixture.cancelLocal = false })
  await dialog.getByRole('button', { name: 'Choose folder' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  expect(await page.evaluate(() => (window as any).workspaceImportFixture.created)).toEqual([{ name: 'JanusX', path: 'C:/Projects/JanusX' }])
})

test('WSL browses folders and validates the typed folder when adding', async ({ page }) => {
  await page.goto('/workspace-import.html')
  await page.getByRole('button', { name: 'Add workspace', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'WSL', exact: true }).click()
  await dialog.getByLabel('WSL distribution').selectOption('Debian')
  await dialog.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(dialog.getByLabel('Directory', { exact: true })).toHaveValue('/home/developer')
  await expect(dialog.getByRole('button', { name: 'readme.txt' })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'projects', exact: true }).click()
  await expect(dialog.getByText('No subfolders in this directory')).toBeVisible()
  await dialog.getByRole('button', { name: 'Parent directory' }).click()
  await expect(dialog.getByRole('button', { name: 'projects', exact: true })).toBeVisible()
  await dialog.getByLabel('Directory', { exact: true }).fill('/home/developer/typed-project')
  await dialog.getByRole('button', { name: 'Add and open' }).click()
  await expect(dialog).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).workspaceImportFixture.created[0])).toMatchObject({
    path: '/home/developer/typed-project', runtime: { kind: 'wsl', distro: 'Debian', root: '/home/developer/typed-project' },
  })
})

test('SSH progressive options, error recovery and busy dismissal protection', async ({ page }) => {
  await page.goto('/workspace-import.html')
  await page.getByRole('button', { name: 'Add workspace', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'SSH', exact: true }).click()
  await expect(dialog.getByLabel('Port', { exact: true })).toBeHidden()
  await expect(dialog.getByRole('button', { name: 'Connect', exact: true })).toBeDisabled()
  await dialog.getByLabel('SSH host').fill('dev-server')
  await dialog.locator('summary').click()
  await dialog.getByLabel('Port', { exact: true }).fill('2222')
  await dialog.getByLabel('Identity file', { exact: true }).fill('C:/keys/dev')
  await page.evaluate(() => { Object.assign((window as any).workspaceImportFixture, { failConnect: true, delay: 700 }) })
  await dialog.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('alert')).toContainText('Could not connect')
  await page.evaluate(() => { Object.assign((window as any).workspaceImportFixture, { failConnect: false, delay: 0 }) })
  await dialog.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(dialog.getByLabel('Directory', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => (window as any).workspaceImportFixture.connections.at(-1))).toMatchObject({ kind: 'ssh', host: 'dev-server', port: 2222, identityFile: 'C:/keys/dev' })
  await dialog.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(dialog.getByLabel('SSH host')).toHaveValue('dev-server')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})

test('keyboard focus stays within visible controls and unavailable WSL cannot connect', async ({ page }) => {
  await page.goto('/workspace-import.html?empty=1')
  await page.getByRole('button', { name: 'Add workspace', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const close = dialog.getByRole('button', { name: 'Close', exact: true })
  await dialog.getByRole('button', { name: 'SSH', exact: true }).click()
  await dialog.getByLabel('SSH host').fill('dev-server')
  await dialog.getByRole('button', { name: 'Connect', exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Connect', exact: true })).toBeFocused()
  await dialog.getByRole('button', { name: 'WSL', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Connect', exact: true })).toBeDisabled()
  await expect(dialog.getByLabel('WSL distribution')).toContainText('No WSL distributions found')
})

for (const theme of ['dark', 'planche']) {
  test(`workspace import layout: ${theme}, compact and desktop`, async ({ page }) => {
    for (const width of [1280, 390]) {
      await page.setViewportSize({ width, height: 720 })
      await page.goto(`/workspace-import.html?theme=${theme}&lang=zh-CN`)
      await page.getByRole('button', { name: 'Add workspace', exact: true }).click()
      const dialog = page.getByRole('dialog')
      for (const source of ['Local', 'WSL', 'SSH']) {
        await dialog.getByRole('button', { name: source, exact: true }).click()
        await expect(dialog).toBeVisible()
        // Wait for the shared modal entrance to settle before measuring and capturing.
        await expect.poll(() => dialog.evaluate(element => element.getAnimations().every(animation => animation.playState === 'finished'))).toBe(true)
        const box = await dialog.boundingBox()
        expect(box!.x).toBeGreaterThanOrEqual(15)
        expect(box!.x + box!.width).toBeLessThanOrEqual(width - 15)
        expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
        await page.screenshot({ path: `artifacts/workspace-import-${theme}-${width}-${source}.png`, animations: 'disabled' })
      }
      await dialog.getByLabel('SSH 主机').fill('dev-server')
      await dialog.getByRole('button', { name: '连接', exact: true }).click()
      await expect(dialog.getByLabel('目标目录')).toBeVisible()
      await page.screenshot({ path: `artifacts/workspace-import-${theme}-${width}-folders.png`, animations: 'disabled' })
      await dialog.getByRole('button', { name: '返回', exact: true }).click()
      await dialog.locator('summary').click()
      await expect(dialog.getByLabel('身份文件', { exact: true })).toBeVisible()
      expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
      await page.screenshot({ path: `artifacts/workspace-import-${theme}-${width}-advanced.png`, animations: 'disabled' })
    }
  })
}
