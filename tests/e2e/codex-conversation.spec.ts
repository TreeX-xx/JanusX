test('keeps history readable during streaming, returns to latest, and grows the composer in a narrow pane', async ({ page }) => {
  await page.setViewportSize({ width: 380, height: 700 })
  await page.goto('/codex-conversation.html')
  await page.getByRole('button', { name: 'Conversation', exact: true }).click()
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  const initialHeight = await input.evaluate(el => el.clientHeight)
  await input.fill('Review the release\nCheck the build\nCheck the tests\nSummarize the changes\nList the follow-up work')
  await expect.poll(() => input.evaluate(el => el.clientHeight)).toBeGreaterThan(initialHeight)
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect.poll(() => input.evaluate(el => el.clientHeight)).toBe(initialHeight)
  await page.evaluate(() => (window as any).codexFixture.delta(Array.from({ length: 40 }, (_, i) => `Review item ${i + 1}: checked the release changes.`).join('\n\n')))
  const history = page.getByRole('region', { name: 'Conversation history' })
  await history.evaluate(el => { el.scrollTop = 0 })
  const latest = page.getByRole('button', { name: 'Back to latest' })
  await expect(latest).toBeVisible()
  await page.evaluate(() => (window as any).codexFixture.delta('\n\nFinal review complete.'))
  await expect.poll(() => history.evaluate(el => el.scrollTop)).toBe(0)
  await latest.focus()
  await page.keyboard.press('Enter')
  await expect(latest).toBeHidden()
  await expect.poll(() => history.evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop)).toBeLessThan(2)
  await expect(page.getByText('Final review complete.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Stop response' }).click()
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/codex-dual-mode/conversation-narrow.png' })
})

