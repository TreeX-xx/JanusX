test('shows pending view feedback, guards input, restores focus and recovers from a rejected switch', async ({ page }) => {
  await page.goto('/codex-conversation.html')
  const conversation = page.getByRole('button', { name: 'Conversation', exact: true })
  const terminal = page.getByRole('button', { name: 'Terminal', exact: true })
  const pane = page.locator('[data-agent-session]')
  const loading = page.getByRole('status').filter({ hasText: 'Switching view' })
  await page.locator('.xterm').evaluate(el => el.setAttribute('data-original', 'yes'))
  await page.evaluate(() => (window as any).codexFixture.holdMode())
  await conversation.click()
  await expect(loading).toBeVisible()
  await expect(pane).toHaveAttribute('aria-busy', 'true')
  await expect(conversation).toBeDisabled()
  await expect(terminal).toBeDisabled()
  await page.keyboard.type('blocked input')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.input)).toEqual([])
  await page.screenshot({ path: 'artifacts/codex-dual-mode/view-switch-loading.png' })
  await page.evaluate(() => (window as any).codexFixture.releaseMode())
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  await expect(input).toBeFocused()
  await expect(loading).toHaveCount(0)
  await input.fill('Keep the transition draft')
  await page.evaluate(() => (window as any).codexFixture.holdMode())
  await terminal.click()
  await expect(loading).toBeVisible()
  await page.keyboard.press('Enter')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual([])
  await page.evaluate(() => (window as any).codexFixture.releaseMode(true))
  await expect(page.getByRole('alert')).toHaveText('Error: Fixture mode switch failed')
  await expect(input).toBeFocused()
  await expect(input).toHaveText('Keep the transition draft')
  await expect(conversation).toHaveAttribute('aria-pressed', 'true')
  await terminal.click()
  await expect(terminal).toBeEnabled()
  await expect(page.locator('.xterm')).toHaveAttribute('data-original', 'yes')
  await expect(page.locator('.xterm-helper-textarea')).toBeFocused()
  expect(await page.evaluate(() => (window as any).codexFixture.calls)).toMatchObject({ create: 0, kill: 0 })
})

