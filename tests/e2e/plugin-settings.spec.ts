import { expect, test } from '@playwright/test'

test('synthetic official market: Blueprint settings appear only after enabling and leave on disable/uninstall', async ({ page }) => {
  await page.goto('/settings.html?tab=experimental&plugin-market&en')
  const navigation = page.locator('[data-tab="extension:official.blueprint/settings"]')
  await expect(navigation).toHaveCount(0)
  await expect(page.locator('[data-tab="knowledge"]')).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: /Blueprint/i })).toHaveCount(0)
  await page.locator('[data-tab="plugins"]').click()
  await page.getByRole('tab', { name: 'Discover plugins', exact: true }).click()
  const card = page.locator('[data-catalog-id="official.blueprint"]')
  await expect(card).toContainText('Official')
  const search = page.getByRole('searchbox', { name: 'Search plugins, features or publishers…' })
  await search.fill('missing-plugin')
  await expect(card).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('No matching plugins')
  await search.fill('  JANUSX  ')
  await expect(card).toBeVisible()
  await search.fill('')
  await page.screenshot({ path: 'artifacts/plugins/market-desktop.png', fullPage: true })
  await card.getByRole('button', { name: 'Install', exact: true }).click()
  // Installed but not enabled: no settings entry, plugin code never loads.
  await expect(card.getByRole('button', { name: 'Installed', exact: true })).toBeVisible()
  await expect(navigation).toHaveCount(0)
  await expect(page.locator('[data-plugin-native]')).toHaveCount(0)
  await page.getByRole('tab', { name: /^Installed/ }).click()
  const installed = page.locator('[data-plugin-id="official.blueprint"]')
  const installedSearch = page.getByRole('searchbox', { name: 'Search installed plugins…' })
  await installedSearch.fill('missing-plugin')
  await expect(installed).toHaveCount(0)
  await installedSearch.fill('blueprint')
  await expect(installed).toBeVisible()
  await installed.getByRole('button', { name: 'Review permissions', exact: true }).click()
  const review = page.getByRole('region', { name: 'Review permissions' })
  await expect(review.getByRole('checkbox')).toHaveCount(0)
  await expect(review).toContainText('all current and future workspaces')
  await page.getByRole('region', { name: 'Review permissions' }).getByRole('button', { name: 'Grant and enable', exact: true }).click()
  await expect(navigation).toBeVisible()
  await installed.getByText('Manage and configure', { exact: true }).click()
  await installed.getByText('Entries and shortcuts', { exact: true }).click()
  const visibleEntry = installed.getByRole('switch', { name: /Show in toolbox/ })
  await expect(visibleEntry).toBeChecked()
  await visibleEntry.uncheck()
  await expect(visibleEntry).not.toBeChecked()
  await visibleEntry.check()
  await expect(visibleEntry).toBeChecked()
  await expect(installed.getByRole('spinbutton')).toHaveCount(0)
  await expect(installed.getByText('open-blueprint', { exact: true })).toHaveCount(0)
  await expect(installed.getByPlaceholder('Not set')).toHaveCount(2)
  await page.setViewportSize({ width: 560, height: 760 })
  await expect(visibleEntry).toBeVisible()
  expect(await installed.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/plugins/settings-entries-narrow.png', fullPage: true })
  await installed.getByRole('button', { name: 'Disable', exact: true }).click()
  await expect(navigation).toHaveCount(0)
  await installed.getByRole('button', { name: 'Review permissions', exact: true }).click()
  await page.getByRole('region', { name: 'Review permissions' }).getByRole('button', { name: 'Grant and enable', exact: true }).click()
  await expect(navigation).toBeVisible()
  await page.getByRole('tab', { name: 'Discover plugins', exact: true }).click()
  await card.getByRole('button', { name: 'Uninstall', exact: true }).click()
  await page.getByRole('alertdialog', { name: 'Uninstall', exact: true }).getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(navigation).toHaveCount(0)
  await expect(page.locator('[data-plugin-settings-page]')).toHaveCount(0)
  await expect(page.locator('[data-plugin-id="official.blueprint"]')).toHaveCount(0)
  await page.getByRole('tab', { name: 'Discover plugins', exact: true }).click()
  await expect(card.getByRole('button', { name: 'Install', exact: true })).toBeEnabled()
})

test('market cards form a grid and reflow in a narrow settings window', async ({ page }) => {
  await page.goto('/settings.html?tab=plugins&plugin-market&plugin-gallery')
  await page.getByRole('tab', { name: '发现插件', exact: true }).click()
  const cards = page.locator('[data-catalog-id]')
  await expect(cards).toHaveCount(3)
  const first = await cards.nth(0).boundingBox()
  const second = await cards.nth(1).boundingBox()
  expect(first!.y).toBe(second!.y)
  expect(second!.x).toBeGreaterThan(first!.x)
  await page.screenshot({ path: 'artifacts/plugins/market-grid-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 560, height: 760 })
  const narrowFirst = await cards.nth(0).boundingBox()
  const narrowSecond = await cards.nth(1).boundingBox()
  expect(narrowSecond!.y).toBeGreaterThan(narrowFirst!.y)
  expect(await page.locator('[data-plugin-settings]').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/plugins/market-grid-narrow.png', fullPage: true })
})
