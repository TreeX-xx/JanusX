import { expect, test } from '@playwright/test'

test('synthetic official market: Blueprint settings appear only after enabling and leave on disable/uninstall', async ({ page }) => {
  await page.goto('/settings.html?tab=experimental&plugin-market&en')
  const navigation = page.locator('[data-tab="extension:official.blueprint/settings"]')
  await expect(navigation).toHaveCount(0)
  await expect(page.locator('[data-tab="knowledge"]')).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: /Blueprint/i })).toHaveCount(0)
  await page.locator('[data-tab="plugins"]').click()
  await page.getByRole('tab', { name: 'Discover plugins', exact: true }).click()
  const card = page.locator('[data-catalog-id="official.blueprint"]')
  await expect(card).toContainText('Official')
  await card.getByRole('button', { name: 'Install', exact: true }).click()
  // Installed but not enabled: no settings entry, plugin code never loads.
  await expect(card.getByRole('button', { name: 'Installed', exact: true })).toBeVisible()
  await expect(navigation).toHaveCount(0)
  await expect(page.locator('[data-plugin-native]')).toHaveCount(0)
  await page.getByRole('tab', { name: /^Installed/ }).click()
  const installed = page.locator('[data-plugin-id="official.blueprint"]')
  await installed.getByRole('button', { name: 'Review permissions and scope', exact: true }).click()
  await page.getByRole('region', { name: 'Review permissions and scope' }).getByRole('button', { name: 'Grant and enable', exact: true }).click()
  await expect(navigation).toBeVisible()
  await installed.getByRole('button', { name: 'Disable', exact: true }).click()
  await expect(navigation).toHaveCount(0)
  await installed.getByRole('button', { name: 'Review permissions and scope', exact: true }).click()
  await page.getByRole('region', { name: 'Review permissions and scope' }).getByRole('button', { name: 'Grant and enable', exact: true }).click()
  await expect(navigation).toBeVisible()
  await page.getByRole('tab', { name: 'Discover plugins', exact: true }).click()
  await card.getByRole('button', { name: 'Uninstall', exact: true }).click()
  await page.getByRole('alertdialog', { name: 'Uninstall', exact: true }).getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(navigation).toHaveCount(0)
  await expect(page.locator('[data-plugin-settings-page]')).toHaveCount(0)
  await expect(page.locator('[data-plugin-id="official.blueprint"]')).toHaveCount(0)
  await page.getByRole('tab', { name: 'Discover plugins', exact: true }).click()
  await expect(card.getByRole('button', { name: 'Install', exact: true })).toBeEnabled()
})
