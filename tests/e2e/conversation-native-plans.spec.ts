import { test, expect } from '@playwright/test'

test('Claude preserves confirmed tasks when native task synchronization fails and recovers on a fresh snapshot', async ({ page }) => {
  await page.setViewportSize({ width: 380, height: 700 })
  await page.goto('/codex-conversation.html?engine=claude&theme=light')
  await page.getByRole('button', { name: 'Conversation', exact: true }).click()
  const input = page.getByRole('combobox', { name: 'Message Claude' })
  await expect(input).toBeFocused()
  await input.fill('Track this work'); await input.press('Enter')
  await page.evaluate(() => (window as any).codexFixture.plan())
  const current = page.getByRole('region', { name: 'Execution plan', exact: true }).last()
  await expect(current.locator('[class*="planSpinner"]')).toHaveCount(1)
  await page.evaluate(() => (window as any).codexFixture.stalePlan())
  await expect(current).toContainText('Task sync unavailable · showing last confirmed progress')
  await expect(current).toContainText('1 / 3 completed')
  await expect(current.locator('[class*="planSpinner"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Terminal', exact: true }).click()
  await page.getByRole('button', { name: 'Conversation', exact: true }).click()
  await expect(current).toContainText('Task sync unavailable')
  await expect(input).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/claude-dual-mode/plan-stale-light.png' })
  await page.evaluate(() => (window as any).codexFixture.plan())
  await expect(current).not.toContainText('Task sync unavailable')
  await expect(current.locator('[class*="planSpinner"]')).toHaveCount(1)
  await page.evaluate(() => (window as any).codexFixture.endPlan('interrupted'))
  await expect(current).toContainText('Execution stopped · progress preserved')
  await expect(current).toContainText('1 / 3 completed')
})

test('completed plans collapse and interrupted plans retain their original steps', async ({ page }) => {
  await page.goto('/codex-conversation.html')
  await page.getByRole('button', { name: 'Conversation', exact: true }).click()
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  await expect(input).toBeFocused()
  await input.fill('Plan this'); await input.press('Enter')
  await page.evaluate(() => (window as any).codexFixture.plan())
  const current = page.getByRole('region', { name: 'Execution plan', exact: true }).last()
  await page.evaluate(() => (window as any).codexFixture.plan(true))
  await expect(current.getByRole('button')).toHaveAttribute('aria-expanded', 'false')
  await expect(current).toContainText('3 / 3 completed')
  await page.evaluate(() => { (window as any).codexFixture.plan(); (window as any).codexFixture.endPlan('interrupted') })
  await expect(current).toContainText('Execution stopped · progress preserved')
  await expect(current).toContainText('1 / 3 completed')
  await current.getByRole('button').click()
  await expect(current.getByText('Run checks', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'artifacts/codex-dual-mode/plan-stopped-dark.png' })
  await page.getByRole('button', { name: 'Remount', exact: true }).click()
  await expect(page.getByText('Execution stopped · progress preserved', { exact: true }).last()).toBeVisible()
})

test('native plan panel preserves collapse, versions and unfinished progress across switching and disconnection', async ({ page }) => {
  await page.setViewportSize({ width: 380, height: 700 })
  await page.goto('/codex-conversation.html?theme=light')
  await page.getByRole('button', { name: 'Conversation', exact: true }).click()
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  await expect(input).toBeFocused()
  await expect(page.getByRole('region', { name: 'Execution plan', exact: true })).toHaveCount(0)
  await input.fill('Build a feature'); await input.press('Enter')
  await page.evaluate(() => (window as any).codexFixture.plan())
  const current = page.getByRole('region', { name: 'Execution plan', exact: true }).last()
  const toggle = current.getByRole('button')
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(current.getByText('1 / 3 completed', { exact: true })).toBeVisible()
  await toggle.click()
  await page.evaluate(() => (window as any).codexFixture.plan())
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: 'Terminal', exact: true }).click()
  await page.getByRole('button', { name: 'Conversation', exact: true }).click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await toggle.click()
  await page.screenshot({ path: 'artifacts/codex-dual-mode/plan-narrow.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.evaluate(() => (window as any).codexFixture.fail())
  await expect(current).toContainText('Disconnected · showing last known plan')
  await page.evaluate(() => (window as any).codexFixture.endPlan('completed'))
  await expect(current).toContainText('Turn ended · unfinished steps remain')
  await expect(current).toContainText('1 / 3 completed')
  await page.getByText('Plan history', { exact: true }).click()
  await expect(page.getByRole('region', { name: 'Execution plan', exact: true })).toHaveCount(2)
})
