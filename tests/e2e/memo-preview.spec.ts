import { expect, test } from '@playwright/test'

test('provides memo by default with retired controls off and removes preview settings', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/memo.html?settings=1')
  const settings = page.getByTestId('experimental-settings')
  await expect(settings.getByRole('checkbox')).toHaveCount(4)
  await expect(settings.getByRole('checkbox', { name: 'Memo', exact: true })).toHaveCount(0)
  await expect(settings.getByRole('checkbox', { name: 'Session management', exact: true })).toHaveCount(0)
  await expect(settings.getByRole('heading', { name: 'Preview · Preview Features' })).toHaveCount(0)
  const trigger = page.getByRole('button', { name: 'Open memo on the left' })
  await expect(trigger).toBeVisible()

  const memoId = '00000000-0000-4000-8000-000000000001'
  await page.evaluate(id => (window as any).memoFixture.bind(id), memoId)
  await trigger.click()
  await expect(page.locator('.memo-panel')).toBeVisible()
  const before = await page.evaluate(() => JSON.stringify((window as any).memoFixture.memos))
  await page.evaluate(() => (window as any).memoFixture.send('Read this memo'))
  await expect.poll(() => page.evaluate(() => (window as any).memoFixture.requests.length)).toBe(1)
  expect(await page.evaluate(() => (window as any).memoFixture.requests.at(-1).memoBinding.memoId)).toBe(memoId)
  expect(await page.evaluate(() => (window as any).memoFixture.requests.at(-1).memoMessageId)).toBeTruthy()

  // Other innovation controls still require confirmation and do not affect memo.
  await settings.getByRole('checkbox', { name: 'Remote collaboration', exact: true }).press('Space')
  await page.getByRole('button', { name: 'Enable feature', exact: true }).click()
  await expect(trigger).toBeVisible()
  await expect(page.locator('.memo-panel')).toBeVisible()
  expect(await page.evaluate(() => (window as any).memoFixture.aborted)).toBe(0)
  expect(await page.evaluate(() => JSON.stringify((window as any).memoFixture.memos))).toBe(before)
  await page.evaluate(() => (window as any).memoFixture.send('Continue in this memo'))
  await expect.poll(() => page.evaluate(() => (window as any).memoFixture.steers.length)).toBe(1)
  expect(await page.evaluate(() => (window as any).memoFixture.steers.at(-1).memoBinding.memoId)).toBe(memoId)
  await page.evaluate(() => (window as any).memoFixture.finish())
  await expect(page.locator('main.janus-chat')).toHaveAttribute('data-streaming', 'false')
  await trigger.click()
  await expect(page.locator('.memo-panel')).not.toBeVisible()
  await page.evaluate(() => (window as any).memoFixture.send('Read the memo while hidden'))
  await expect.poll(() => page.evaluate(() => (window as any).memoFixture.requests.length)).toBe(2)
  expect(await page.evaluate(() => (window as any).memoFixture.requests.at(-1).memoBinding.memoId)).toBe(memoId)
})
