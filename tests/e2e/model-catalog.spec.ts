import { test, expect } from '@playwright/test'

for (const theme of ['dark', 'planche']) {
  test(`empty catalog and unmatched searches in ${theme}`, async ({ page }) => {
    await page.goto(`/model-catalog.html?empty&theme=${theme}`)
    const emptyCatalog = page.getByRole('status').filter({ hasText: '暂无模型' })
    await expect(emptyCatalog).toContainText('点击“更新目录”获取模型')
    await expect(emptyCatalog).toHaveCSS('align-items', 'flex-start')
    await page.getByRole('button', { name: '更新目录' }).click()
    await expect(page.getByText('Reasoning Pro', { exact: true })).toBeVisible()
    const search = page.getByRole('searchbox')
    await search.fill('unmatched')
    await expect(page.getByRole('status').filter({ hasText: '未找到匹配的模型' })).toBeVisible()
    await expect(emptyCatalog).toHaveCount(0)
    await search.fill('')
    await expect(page.getByText('Reasoning Pro', { exact: true })).toBeVisible()
  })

  test(`model capabilities, cache prices and tier rules in ${theme}`, async ({ page }) => {
    await page.goto(`/model-catalog.html?theme=${theme}`)
    await page.getByText('Reasoning Pro', { exact: true }).click()
    await expect(page.getByRole('heading', { name: '上下文与能力' })).toBeVisible()
    const pricing = page.getByRole('region', { name: '定价与特殊价格' }).first()
    await expect(pricing.getByText('$0.2', { exact: true })).toBeVisible()
    await pricing.getByText('输入达到 200,000 tokens 的阶梯价格').click()
    await expect(pricing.getByText('$15', { exact: true })).toBeVisible()
    await pricing.getByText('其他计费与原始规则').click()
    await expect(pricing.getByText('0.01', { exact: true })).toBeVisible()
    await page.screenshot({ path: `artifacts/model-catalog/${theme}.png`, fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await expect(pricing).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `artifacts/model-catalog/${theme}-narrow.png`, fullPage: true })
    await page.getByRole('searchbox').fill('minimal')
    await expect(page.getByText('Reasoning Pro', { exact: true })).toHaveCount(0)
    await page.getByText('Minimal', { exact: true }).click()
    await expect(page.getByText('未提供', { exact: true })).toHaveCount(4)
    await page.getByRole('button', { name: '更新目录' }).click()
    await expect(page.getByText('已更新 2 个模型')).toBeVisible()
  })
}

test('vendor search restores browsing position, disclosure state and keyboard focus', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/model-catalog.html?browse')
  const main = page.locator('main')
  await main.evaluate(el => Object.assign(el.style, { width: '440px', height: '540px', overflowY: 'auto' }))
  const vendor = page.getByRole('button', { name: /DeepSeek 30/i })
  await expect(vendor.locator('img')).toBeVisible()
  const model = page.getByRole('button', { name: /^Model 2 custom/ })
  await model.focus()
  await model.press('Enter')
  await expect(model).toHaveAttribute('aria-expanded', 'true')
  const copy = page.getByRole('button', { name: '复制模型 ID custom/model-2', exact: true })
  await copy.click()
  await expect(page.getByText('已复制', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('custom/model-2')
  await expect(model).toHaveAttribute('aria-expanded', 'true')
  const heading = page.getByRole('heading', { name: '定价与特殊价格' })
  const capabilities = page.getByRole('heading', { name: '上下文与能力' })
  expect((await heading.boundingBox())!.y).toBeGreaterThan((await capabilities.boundingBox())!.y)
  await main.evaluate(el => { el.scrollTop = 360 })
  const search = page.getByRole('searchbox')
  await search.fill('deepseek')
  await expect(vendor).toBeVisible()
  await expect(model).toHaveAttribute('aria-expanded', 'false')
  await search.fill('no matching entry')
  await page.getByRole('status').getByRole('button', { name: '清空搜索' }).click()
  await expect(search).toBeFocused()
  await expect(model).toHaveAttribute('aria-expanded', 'true')
  expect(await main.evaluate(el => el.scrollTop)).toBe(360)
  expect(await main.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
})

test('bundled catalog renders provider artwork and long model identities', async ({ page }) => {
  await page.goto('/model-catalog.html?bundled&theme=planche')
  const search = page.getByRole('searchbox')
  await search.fill('deepseek')
  const vendor = page.getByRole('button', { name: /^deepseek \d+$/i })
  await expect(vendor.locator('img')).toBeVisible()
  await expect.poll(() => vendor.locator('img').evaluate(img => (img as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await page.screenshot({ path: 'artifacts/model-catalog/bundled-search.png' })
  await page.setViewportSize({ width: 360, height: 740 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
