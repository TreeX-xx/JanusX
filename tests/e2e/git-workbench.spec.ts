test('search, list/tree and staging keep an explicit staged-only commit', async ({ page }) => {
  const { panel } = await open(page)
  const search = panel.getByRole('textbox', { name: '搜索文件…' })
  await search.fill('file-003')
  await panel.getByRole('button', { name: '文件列表', exact: true }).click()
  const file = panel.getByRole('button', { name: 'src/components/file-003.tsx', exact: true })
  await file.click()
  await expect(panel.getByTestId('git-diff-detail')).toContainText("+export const view = 'tabs'")
  await file.locator('..').getByRole('button', { name: '暂存更改', exact: true }).click()
  await expect(panel.getByRole('button', { name: '提交已暂存 · 4', exact: true })).toBeDisabled()
  await panel.getByRole('textbox', { name: '提交标题…' }).fill('Commit only staged files')
  await panel.getByRole('button', { name: '详细说明', exact: true }).click()
  await panel.getByRole('textbox', { name: '详细说明', exact: true }).fill('Keep unrelated changes')
  await page.evaluate(() => (window as any).gitWorkbenchFixture.failCommit(true))
  await panel.getByRole('button', { name: '提交已暂存 · 4', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('Commit hook rejected')
  await expect(panel.getByRole('textbox', { name: '提交标题…' })).toHaveValue('Commit only staged files')
  await page.evaluate(() => (window as any).gitWorkbenchFixture.failCommit(false))
  await panel.getByRole('button', { name: '提交已暂存 · 4', exact: true }).click()
  await expect(panel.getByRole('textbox', { name: '提交标题…' })).toHaveValue('')
  await expect(panel.getByRole('button', { name: '提交已暂存 · 0', exact: true })).toBeDisabled()
  expect((await operations(page)).filter((op: any) => op.action === 'stage')).toHaveLength(1)
  expect((await operations(page)).filter((op: any) => op.action === 'commit').at(-1).value).toBe('Commit only staged files\n\nKeep unrelated changes')
})

