test('discard and remote actions remain reviewable before execution', async ({ page }) => {
  const { panel } = await open(page)
  await panel.getByRole('textbox', { name: '搜索文件…' }).fill('file-004')
  const row = panel.getByRole('button', { name: 'src/components/file-004.tsx', exact: true }).locator('..')
  await row.hover()
  await row.getByRole('button', { name: '文件操作：src/components/file-004.tsx' }).click()
  await page.getByRole('button', { name: '放弃更改', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '放弃更改？' })
  await expect(dialog).toContainText('src/components/file-004.tsx')
  expect((await operations(page)).filter((op: any) => op.action === 'discard')).toEqual([])
  await dialog.getByRole('button', { name: '放弃更改', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await panel.getByRole('button', { name: /推送/ }).click()
  const remote = page.getByRole('dialog', { name: '确认 Push' })
  await expect(remote).toContainText('origin/main')
  expect((await operations(page)).filter((op: any) => op.action === 'push')).toEqual([])
  await remote.getByRole('button', { name: '确认 Push', exact: true }).click()
  await expect.poll(async () => (await operations(page)).filter((op: any) => op.action === 'push').length).toBe(1)
})
