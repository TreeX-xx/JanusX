    await page.mouse.move(350, 20)
    await panel.screenshot({ path: test.info().outputPath(`git-history-${theme}-${width}.png`) })
    await expect.poll(() => panel.evaluate(el => el.scrollWidth - el.clientWidth)).toBe(0)
