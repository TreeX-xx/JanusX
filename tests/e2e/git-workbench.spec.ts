import { expect, test, type Page } from '@playwright/test'

async function open(page: Page, theme = 'dark', width = 360) {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`/git-workbench.html?theme=${theme}&panel=${width}`)
  const panel = page.locator('#right-tool-panel-git')
  await expect(panel).toBeVisible()
  await expect(panel.locator('[data-workspace-transition]')).toHaveAttribute('aria-busy', 'false')
  await expect(panel.getByRole('tab', { name: /变更/ })).toContainText('500')
  return { panel, errors }
}
const operations = (page: Page) => page.evaluate(() => (window as any).gitWorkbenchFixture.operations())

