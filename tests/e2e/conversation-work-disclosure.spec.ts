import { expect, test } from '@playwright/test'

test('terminal conversation can return to the top of a long expanded process', async ({ page }) => {
  await page.setViewportSize({ width: 380, height: 780 })
  await page.goto('/codex-conversation.html?initialView=conversation')
  await expect(page.getByRole('button', { name: 'Conversation', exact: true })).toBeEnabled()
  await page.evaluate(() => (window as any).codexFixture.progressSnapshot({
    turnId: null,
    items: Array.from({ length: 40 }, (_, index) => ({
      id: `check-${index}`, turnId: 'process', type: 'commandExecution', text: `Check ${index}`, status: 'completed',
    })),
  }))
  const toggle = page.locator('.conversation-work-toggle')
  const returnButton = page.getByRole('button', { name: 'Back to process start' })
  const scroller = page.getByRole('region', { name: 'Conversation history' })
  await toggle.click()
  await expect(returnButton).toBeInViewport()
  await expect(returnButton).toHaveText('')
  await expect(returnButton).toHaveAttribute('title', 'Back to process start')
  expect(await returnButton.evaluate(button => {
    const body = button.closest('.conversation-work')!.querySelector('.conversation-work-body')!
    const textStart = body.getBoundingClientRect().left + parseFloat(getComputedStyle(body).paddingInlineStart)
    return button.getBoundingClientRect().right <= textStart
  })).toBe(true)
  await scroller.evaluate(element => { element.scrollTop = 0 })
  await expect(toggle).toBeInViewport()
  await expect(returnButton).toBeHidden()
  await scroller.evaluate(element => { element.scrollTop = element.scrollHeight / 2 })
  await expect(toggle).not.toBeInViewport()
  await expect(returnButton).toBeInViewport()
  await returnButton.click()
  await expect(toggle).toBeFocused()
  await expect(toggle).toBeInViewport({ ratio: 1 })
  await page.keyboard.press('Enter')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
})

for (const engine of ['codex', 'claude', 'opencode', 'pi', 'dsh']) {
  test(`${engine}: history limits, output limits and unknown states stay distinct`, async ({ page }) => {
    await page.goto(`/codex-conversation.html?initialView=conversation&engine=${engine}`)
    await expect(page.getByRole('button', { name: 'Conversation', exact: true })).toBeEnabled()
    const show = (kind: string) => page.evaluate(kind => (window as any).codexFixture.workTruncated(kind), kind)
    const toggle = page.locator('.conversation-work-toggle')
    await show('history')
    await expect(toggle).toContainText('npm test')
    await expect(toggle).not.toContainText('truncated')
    await show('output')
    await expect(toggle).toContainText('Output truncated')
    await show('unknown')
    await expect(toggle).toContainText('Status unconfirmed')
    await expect(toggle).not.toContainText('truncated')
  })
  test(`${engine}: live duration survives work updates and settles into one turn total`, async ({ page }) => {
    await page.clock.install()
    await page.goto(`/codex-conversation.html?initialView=conversation&engine=${engine}`)
    await expect(page.getByRole('button', { name: 'Conversation', exact: true })).toBeEnabled()
    await page.clock.pauseAt(await page.evaluate(() => Date.now() + 10_000))
    const preview = (stage: string) => page.evaluate(stage => (window as any).codexFixture.workPreview(stage), stage)
    await preview('start')
    const running = page.locator('[data-conversation-running]')
    const duration = running.getByLabel(/^Run duration /)
    const total = page.getByLabel(/^Turn time /)
    await expect(running).toContainText('read workspace')
    await expect(duration).toHaveText('0:00')
    const original = await duration.elementHandle()
    const toggle = page.locator('.conversation-work-toggle')
    for (const [index, stage] of ['update', 'idle', 'update'].entries()) {
      await preview(stage)
      await toggle.click()
      await expect(running).toContainText(stage === 'idle' ? /^Running\s*·/ : 'check workspace')
      await expect(duration).toBeVisible()
      expect(await duration.evaluate((node, previous) => node === previous, original)).toBe(true)
      await page.clock.runFor(1000)
      await expect(duration).toHaveText(`0:0${index + 1}`)
    }
    await expect(total).toHaveCount(0)
    await preview('finish')
    await expect(running).toHaveCount(0)
    await expect(total).toHaveCount(1)
    await expect(total).toHaveText('Turn time 0:03')
    await page.getByRole('button', { name: 'Remount' }).click()
    await page.clock.runFor(1000)
    await expect(total).toHaveText('Turn time 0:03')
  })

  test(`${engine}: live work stays compact, preserves choices and exposes failures`, async ({ page }) => {
    await page.goto(`/codex-conversation.html?initialView=conversation&engine=${engine}`)
    await expect(page.getByRole('button', { name: 'Conversation', exact: true })).toBeEnabled()
    const preview = (stage: string) => page.evaluate(stage => (window as any).codexFixture.workPreview(stage), stage)
    await preview('start')
    const toggle = page.locator('.conversation-work-toggle')
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await expect(toggle).toContainText('Running')
    await expect(page.getByText('I will inspect the workspace.', { exact: true })).toBeVisible()
    await expect(page.locator('.conversation-work summary')).toHaveCount(0)
    if (engine === 'codex') {
      await page.evaluate(() => (window as any).codexFixture.workApproval())
      await expect(toggle).toContainText('Needs approval')
      await expect(toggle).toHaveAttribute('aria-expanded', 'false')
      await expect(page.getByText('Allow workspace inspection', { exact: true })).toBeVisible()
      await preview('start')
    }
    await toggle.click()
    const detail = page.locator('.conversation-work details').first()
    await detail.locator('summary').click()
    await expect(detail).toHaveAttribute('open', '')
    await preview('update')
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await expect(toggle).toContainText('2 activities')
    await expect(toggle).toContainText('1 failed')
    await expect(detail).toHaveAttribute('open', '')
    await toggle.click()
    await preview('finish')
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await expect(toggle).toContainText('1 failed')
    await expect(toggle).toContainText('Finished')
    await expect(toggle).toContainText('check workspace')
    await expect(toggle).not.toContainText('Incomplete record')
    await expect(page.getByText('The check finished with a read error.', { exact: true })).toBeVisible()
    await toggle.click()
    await expect(detail).toHaveAttribute('open', '')
    await expect(detail.locator('pre')).toContainText('Raw command output')
    if (engine === 'codex') {
      await page.setViewportSize({ width: 380, height: 780 })
      await expect(toggle).toBeVisible()
      expect(await toggle.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
      await page.screenshot({ path: 'artifacts/work-disclosure-narrow.png' })
    }
  })
}
