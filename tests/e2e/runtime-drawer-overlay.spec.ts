import { expect, test } from '@playwright/test'

test('context details are independent and Escape dismisses them before the usage overlay', async ({ page }) => {
  await page.goto('/pane-tabs.html?single&usage')
  const toggle = page.getByRole('button', { name: 'Toggle usage panel', exact: true })
  const indicator = page.locator('[data-context-indicator]')
  const tip = page.getByRole('tooltip')
  await indicator.click()
  await page.mouse.move(0, 0)
  await expect(tip).toContainText('196,000')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await indicator.click()
  await expect(tip).toHaveCount(0)
  await toggle.click()
  await indicator.click()
  await expect(tip).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(tip).toHaveCount(0)
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(toggle).toBeFocused()
  await expect.poll(() => page.locator('#drawer-runtime-panel').evaluate(el => el.inert)).toBe(true)
  await expect(page.locator('#drawer-runtime-panel')).toBeHidden()
  await toggle.press('Tab')
  await expect(indicator).toBeFocused()
  await expect(tip).toContainText('196,000')
})

test('opening, details and resizing leave terminal geometry and scrollback unchanged', async ({ page }) => {
  await page.goto('/pane-tabs.html?single&usage&navigation')
  await page.waitForFunction(() => (window as any).paneFixture.buffersReady())
  const screen = page.locator('.xterm-screen').first()
  await screen.hover()
  await page.mouse.wheel(0, -1000)
  await expect.poll(() => page.evaluate(() => {
    const state = (window as any).paneFixture.terminalState('a')
    return state.viewportY < state.baseY
  })).toBe(true)
  const before = await page.evaluate(() => (window as any).paneFixture.terminalState('a'))
  const bounds = await page.locator('[data-pane-host]').boundingBox()
  const toggle = page.getByRole('button', { name: 'Toggle usage panel', exact: true })
  await toggle.click()
  const panel = page.getByRole('region', { name: 'Usage', exact: true })
  const details = panel.locator('[data-runtime-card]').first().locator('details')
  await details.locator('summary').click()
  await expect(details).toContainText('196,000')
  const handle = panel.getByRole('separator')
  await handle.focus()
  await handle.press('ArrowDown')
  expect(await page.locator('[data-pane-host]').boundingBox()).toEqual(bounds)
  expect(await page.evaluate(() => (window as any).paneFixture.terminalState('a'))).toEqual(before)
  await panel.getByRole('button', { name: 'Close usage panel' }).click()
  await expect(toggle).toBeFocused()
  await toggle.click()
  await expect(details).toHaveAttribute('open')
  await toggle.click()
  await toggle.click()
  await expect(panel).toBeVisible()
  await page.waitForTimeout(250)
  await expect(panel).toBeVisible()
  await screen.click({ position: { x: 20, y: 20 } })
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  expect(await page.locator('[data-pane-host]').boundingBox()).toEqual(bounds)
})

for (const [width, height, theme] of [[1440, 900, 'dark'], [1280, 800, 'white'], [800, 520, 'planche'], [390, 844, 'planche'], [360, 740, 'dark']] as const) {
  test(`usage overlay stays bounded and scrolls internally at ${width}×${height} ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width, height })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto(`/pane-tabs.html?single&usage&theme=${theme}`)
    await page.evaluate(() => (window as any).paneFixture.changeLanguage('zh-CN'))
    const toggle = page.getByRole('button', { name: '切换用量面板', exact: true })
    const bounds = await page.locator('[data-pane-host]').boundingBox()
    await toggle.click()
    const panel = page.getByRole('region', { name: '用量', exact: true })
    await expect(panel).toHaveCSS('animation-name', 'none')
    await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
    const box = (await panel.boundingBox())!
    expect(box.x).toBeGreaterThanOrEqual(0)
    expect(box.y).toBeGreaterThanOrEqual(0)
    expect(box.x + box.width).toBeLessThanOrEqual(width)
    expect(box.height).toBeLessThanOrEqual(height * .6 + 1)
    expect(await panel.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    const grid = panel.locator('[data-runtime-card]').first().locator('..')
    const columns = await grid.evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length)
    expect(columns).toBe(width > 1000 ? 3 : width > 600 ? 2 : 1)
    await panel.locator('[data-runtime-card]').first().locator('summary').click()
    const scroller = grid.locator('..')
    await scroller.evaluate(el => { el.scrollTop = el.scrollHeight })
    await expect(panel.getByRole('button', { name: '收起用量面板' })).toBeInViewport()
    expect(await page.locator('[data-pane-host]').boundingBox()).toEqual(bounds)
    await page.screenshot({ path: test.info().outputPath(`usage-${theme}-${width}.png`) })
    await panel.getByRole('button', { name: '收起用量面板' }).click()
    await toggle.click()
    await expect.poll(() => scroller.evaluate(el => el.scrollTop)).toBe(0)
    await page.screenshot({ path: test.info().outputPath(`usage-${theme}-${width}-top.png`) })
    await toggle.press('Shift+Tab')
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  })
}
