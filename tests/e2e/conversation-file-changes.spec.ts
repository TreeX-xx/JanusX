import { expect, test } from '@playwright/test'

for (const theme of ['dark', 'light']) test(`turn files preview on hover and open in the right panel: ${theme}`, async ({ page }) => {
  await page.goto(`/codex-conversation.html?theme=${theme}&initialView=conversation`)
  await page.evaluate(() => (window as any).codexFixture.designPreview())
  const work = page.locator('.conversation-work-toggle')
  const trigger = page.locator('[data-history-key="preview"] [data-turn-files="preview"]')
  const panel = page.getByRole('complementary', { name: 'Files changed this turn (1)' })
  const file = panel.locator('details')
  const path = 'src/main/terminal/opencode-conversation.ts'
  await expect(work).toHaveAttribute('aria-expanded', 'false')
  await trigger.hover()
  await expect(page.getByRole('tooltip')).toContainText(path)
  await expect(panel).toHaveCount(0)
  await trigger.press('Enter')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(file.locator('summary')).toContainText(path)
  const transcript = page.locator('[data-history-key="preview"]')
  await expect(transcript.locator('[data-turn-files-panel]')).toHaveCount(0)
  const row = (await transcript.boundingBox())!
  expect((await panel.boundingBox())!.x).toBeGreaterThanOrEqual(row.x + row.width - 1)
  await expect(file).not.toHaveAttribute('open', '')
  await expect(file.locator('pre')).toHaveCount(0)
  await file.locator('summary').press('Enter')
  await expect(file.locator('pre')).toContainText('+ this.updateSettings(session.data.model)')
  await page.evaluate(() => (window as any).codexFixture.delta(' Updated'))
  await expect(file).toHaveAttribute('open', '')
  await page.screenshot({ path: `artifacts/conversation-files-desktop-${theme}.png` })
  await file.locator('summary').press('Escape')
  await expect(panel).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(file.locator('pre')).toBeVisible()
  await panel.getByRole('button', { name: path, exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.calls.opens)).toEqual(['C:/fixture/' + path])
  await expect(work).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: 'Remount', exact: true }).click()
  await expect(panel).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 720 })
  await trigger.click()
  await expect(file.locator('summary')).toBeInViewport()
  await expect(file.locator('pre')).toHaveCount(0)
  await file.locator('summary').press('Enter')
  await expect(file.locator('pre')).toBeInViewport()
  await file.locator('summary').press('Enter')
  await expect(file.locator('pre')).toBeHidden()
  await file.locator('summary').press('Enter')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `artifacts/conversation-files-${theme}.png` })
  await panel.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(trigger).toBeFocused()
  await page.evaluate(() => (window as any).codexFixture.editPreview())
  await expect(page.locator('[data-turn-files]')).toHaveCount(0)
})

test('a reply opens a collapsed file list in receipt order and reveals only the chosen patches', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  await page.getByRole('combobox', { name: 'Message Codex' }).waitFor()
  await page.evaluate(async () => {
    const fixture = (window as any).codexFixture
    await fixture.changeLanguage('zh-CN')
    fixture.progressSnapshot({ turnId: null, items: [
      { id: 'req', turnId: 'settings', type: 'userMessage', status: 'completed', text: '让对话和终端共用模型设置。' },
      { id: 'edit', turnId: 'settings', type: 'fileChange', status: 'completed', text: '', files: [
        { path: 'assets/settings.png', diff: '' },
        { path: 'src/session/settings.ts', diff: '@@ -12,3 +12,4 @@\n function updateSettings(session) {\n-  setModel(session.model)\n+  setModel(session.settings.model)\n+  setEffort(session.settings.effort)\n }' },
        { path: 'src/terminal/model.ts', diff: '@@ -8 +8 @@\n-return model\n+return settings.model' },
      ] },
      { id: 'result', turnId: 'settings', type: 'agentMessage', status: 'completed', text: '对话和终端现在共用一份模型设置。切换模型或推理强度后，两边会同步更新。' },
    ] })
  })
  const trigger = page.locator('[data-history-key="settings"] [data-turn-files="settings"]')
  await trigger.click()
  const panel = page.locator('[data-turn-files-panel="settings"]')
  await expect(panel.locator('summary')).toHaveCount(3)
  await expect(panel.locator('details[open], pre')).toHaveCount(0)
  await expect(panel.locator('summary').first()).toContainText('assets/settings.png')
  await page.screenshot({ path: 'artifacts/conversation-files-review-zh.png', animations: 'disabled' })
  const settings = panel.locator('summary').filter({ hasText: 'settings.ts' })
  await settings.click()
  await expect(panel.locator('pre')).toHaveCount(1)
  await expect(panel.locator('pre')).toBeInViewport()
  await expect(panel.locator('pre')).toContainText('+  setEffort(session.settings.effort)')
  await expect(panel.locator('pre [data-change=add]')).toHaveCount(2)
  await expect(panel.locator('pre [data-change=delete]')).toHaveCount(1)
  await expect(trigger.locator('.diff-counts')).toHaveCount(0)
  await panel.locator('summary').filter({ hasText: 'model.ts' }).click()
  await expect(panel.locator('pre[data-side-path="src/terminal/model.ts"]')).toBeVisible()
  await expect(panel.locator('pre')).toHaveCount(2)
  await settings.click()
  await expect(panel.locator('pre')).toHaveCount(1)
  await panel.getByRole('button', { name: '关闭', exact: true }).click()
  await trigger.click()
  await expect(panel.locator('pre')).toHaveCount(1)
  await expect(panel.locator('pre[data-side-path="src/terminal/model.ts"]')).toBeVisible()
})
