import { expect, test } from '@playwright/test'

for (const theme of ['dark', 'light']) test(`turn file summary stays visible outside collapsed work: ${theme}`, async ({ page }) => {
  test.setTimeout(60_000)
  await page.goto(`/codex-conversation.html?theme=${theme}`)
  await page.getByRole('button', { name: 'Conversation', exact: true }).click()
  await page.evaluate(() => (window as any).codexFixture.designPreview())
  const work = page.getByRole('button', { name: 'Work log', exact: true })
  const changes = page.locator('[data-turn-files="preview"]')
  await expect(work).toHaveAttribute('aria-expanded', 'false')
  await expect(changes.locator(':scope > summary')).toHaveText('Files changed this turn (1)View changes')
  await changes.locator(':scope > summary').click()
  const file = changes.locator('details')
  await expect(file.locator('summary')).toContainText('src/main/terminal/opencode-conversation.ts')
  await expect(file).not.toHaveAttribute('open', '')
  await expect(changes.locator('pre')).toBeHidden()
  await file.locator('summary').press('Enter')
  await expect(changes.locator('pre')).toContainText('+ this.updateSettings(session.data.model)')
  await page.evaluate(() => (window as any).codexFixture.delta(' Updated'))
  await expect(file).toHaveAttribute('open', '')
  await changes.locator(':scope > summary').click()
  await changes.locator(':scope > summary').click()
  await expect(changes.locator('pre')).toBeVisible()
  await changes.getByRole('button', { name: 'src/main/terminal/opencode-conversation.ts', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.calls.opens)).toEqual(['C:/fixture/src/main/terminal/opencode-conversation.ts'])
  await expect(work).toHaveAttribute('aria-expanded', 'false')
  await file.locator('summary').click()
  await expect(changes.locator('pre')).toBeHidden()
  await page.getByRole('button', { name: 'Remount', exact: true }).click()
  await expect(page.locator('[data-turn-files="preview"] > summary')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 720 })
  await page.locator('[data-turn-files="preview"] > summary').click()
  await expect(file.locator('summary')).toBeVisible()
  await expect(file.locator('pre')).toBeHidden()
  await file.locator('summary').scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `artifacts/conversation-files-${theme}.png` })
  await page.evaluate(() => (window as any).codexFixture.editPreview())
  await expect(page.locator('[data-turn-files]')).toHaveCount(0)
})
