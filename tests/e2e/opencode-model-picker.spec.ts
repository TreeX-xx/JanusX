import { test, expect } from '@playwright/test'

for (const theme of ['dark', 'light']) test(`${theme}: OpenCode groups native providers inside the shared picker and keeps exact model identity`, async ({ page }) => {
  await page.setViewportSize({ width: 380, height: 740 })
  await page.goto(`/codex-conversation.html?engine=opencode&initialView=conversation&theme=${theme}`)
  await page.evaluate(() => (window as any).codexFixture.providerModels())
  const draft = page.locator('[data-conversation-input]')
  await draft.fill('Keep my draft')
  const trigger = page.getByRole('button', { name: 'Choose model', exact: true })
  await expect(trigger).toContainText('OpenCode Go')
  await trigger.click()
  const picker = page.locator('[data-panel=model]')
  const search = page.getByRole('combobox', { name: 'Search options', exact: true })
  const provider = page.getByRole('combobox', { name: 'Provider', exact: true })
  await expect(picker.locator('[data-provider]')).toHaveText(['OpenCode Go', 'OpenCode Zen', 'Team gateway', 'Company gateway with a very long provider name'])
  await expect(picker.getByRole('option', { name: 'Shared model · OpenCode Go', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(picker.getByRole('option', { name: 'Shared model · OpenCode Zen', exact: true })).toHaveAttribute('title', 'opencode/shared')
  await expect(picker.locator('[role=option] small')).toHaveCount(0)
  const switchBounds = await page.getByRole('button', { name: 'Conversation', exact: true }).boundingBox()
  const pickerBounds = await picker.boundingBox()
  expect(pickerBounds!.y).toBeGreaterThan(switchBounds!.y + switchBounds!.height)
  await page.getByRole('button', { name: 'Refresh models', exact: true }).click()
  expect(await page.evaluate(() => (window as any).codexFixture.calls.commands.some((c: any) => c.type === 'models'))).toBe(true)
  await picker.screenshot({ path: `artifacts/opencode-model-picker/${theme}-grouped.png` })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await search.fill('zen')
  await expect(picker.locator('[role=option]')).toHaveCount(1)
  await search.fill('team/local')
  await expect(picker.getByRole('option', { name: 'Local model · Team gateway', exact: true })).toBeVisible()
  await search.fill('')
  await provider.selectOption('team')
  await expect(search).toBeFocused()
  await expect(picker.locator('[role=option]')).toHaveCount(2)
  await search.fill('not-found')
  await expect(picker.locator('[role=option]')).toHaveCount(0)
  await search.press('Enter')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.settings)).toEqual([])
  await search.fill('')
  await search.press('ArrowDown'); await search.press('Enter')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.settings)).toEqual([{ model: 'team/local/special', effort: 'default' }])
  await expect(draft).toHaveText('Keep my draft')
  await expect(trigger).toContainText('Team gateway')
  await trigger.click()
  await expect(provider).toHaveValue('')
  await provider.selectOption('edge')
  await search.press('Enter')
  await expect(trigger.locator('small')).toHaveAttribute('title', 'Company gateway with a very long provider name')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual([])
})

test('slash model selection searches provider names and preserves the current choice on failure', async ({ page }) => {
  await page.goto('/codex-conversation.html?engine=opencode&initialView=conversation')
  await page.evaluate(() => (window as any).codexFixture.providerModels())
  const input = page.locator('[data-conversation-input]')
  await input.fill('/model Team gateway')
  await expect(page.locator('[data-panel=model] [role=option]')).toHaveCount(2)
  await page.evaluate(() => (window as any).codexFixture.settingsFail(true))
  await input.press('Enter')
  await expect(input).toHaveText('/model Team gateway')
  await expect(page.getByRole('button', { name: 'Choose model', exact: true })).toContainText('OpenCode Go')
  await page.evaluate(() => (window as any).codexFixture.settingsFail(false))
  await input.press('Enter')
  await expect(input).toHaveText('')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.settings)).toEqual([{ model: 'team/shared', effort: 'default' }])
})
