import { expect, test } from '@playwright/test'

for (const theme of ['planche', 'dark']) {
  test(`rail feedback precedes activation and rapid switches coalesce in ${theme}`, async ({ page }) => {
    await page.clock.install({ time: new Date('2026-10-19T00:00:00Z') })
    await page.goto(`/tool-palette.html?theme=${theme}`)
    await expect(page.locator('#right-tool-panel-files').getByText('README.md', { exact: true })).toBeVisible()
    await page.clock.pauseAt(new Date('2026-10-19T00:01:00Z'))
    const rail = page.getByRole('toolbar')
    const git = rail.getByRole('button', { name: /Git/ })
    const sessions = rail.getByRole('button', { name: /会话/ })
    await git.dispatchEvent('click')
    await page.clock.runFor(32)
    // A pending click must not activate a heavy intermediate panel.
    expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().active)).toBe('files')
    await expect(git).toHaveAttribute('data-pending', 'true')
    const marker = page.getByTestId('right-tool-rail-indicator')
    const startY = (await rail.locator('[data-rail-tool="files"]').boundingBox())!.y
    await expect.poll(async () => (await marker.boundingBox())!.y).toBeGreaterThan(startY)
    for (const button of [sessions, git, sessions]) {
      await button.dispatchEvent('click')
      await page.clock.runFor(32)
    }
    await page.clock.runFor(160)
    await expect(sessions).toHaveAttribute('aria-pressed', 'true')
    await expect(rail).toHaveAttribute('aria-busy', 'false')
    expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().toolActivations)).toEqual(['sessions'])
    await expect.poll(async () => Math.abs((await marker.boundingBox())!.y - (await sessions.boundingBox())!.y)).toBeLessThan(0.5)
    await page.screenshot({ path: test.info().outputPath(`rail-feedback-${theme}.png`) })
  })
}

test('rail reversals cancel work while a fresh active-tool click still collapses and expands', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-19T00:00:00Z') })
  await page.goto('/tool-palette.html')
  await expect(page.locator('#right-tool-panel-files').getByText('README.md', { exact: true })).toBeVisible()
  await page.clock.pauseAt(new Date('2026-10-19T00:01:00Z'))
  const rail = page.getByRole('toolbar')
  const files = rail.getByRole('button', { name: /文件/ })
  const git = rail.getByRole('button', { name: /Git/ })
  const sessions = rail.getByRole('button', { name: /会话/ })
  await git.dispatchEvent('click')
  await page.clock.runFor(32)
  await files.dispatchEvent('click')
  await page.clock.runFor(200)
  await expect(page.locator('#right-tool-panel-files')).toBeVisible()
  await expect(rail).toHaveAttribute('aria-busy', 'false')
  await files.dispatchEvent('click')
  await page.clock.runFor(400)
  await expect(page.locator('[id^="right-tool-panel-"]:visible')).toHaveCount(0)
  await files.dispatchEvent('click')
  await page.clock.runFor(400)
  await expect(page.locator('#right-tool-panel-files')).toBeVisible()
  // Closing a pending target must not reopen it after the deadline.
  await git.dispatchEvent('click')
  await page.clock.runFor(32)
  await page.evaluate(() => (window as any).builtinExtensionFixture.close('git'))
  await page.clock.runFor(200)
  await expect(page.locator('#right-tool-panel-git')).toHaveCount(0)
  // Disabling a contribution while it is pending cancels activation too.
  await sessions.dispatchEvent('click')
  await page.clock.runFor(32)
  await page.evaluate(() => (window as any).builtinExtensionFixture.disable('sessions'))
  await page.clock.runFor(200)
  await expect(sessions).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().toolActivations)).toEqual([])
  // A still-registered closed tool can be reopened through the rail.
  await git.dispatchEvent('click')
  await page.clock.runFor(160)
  await expect(page.locator('#right-tool-panel-git')).toBeVisible()
})

test('rail pending work cancels on collapse and external activation; repeated targets keep their deadline', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-19T00:00:00Z') })
  await page.goto('/tool-palette.html')
  await expect(page.locator('#right-tool-panel-files').getByText('README.md', { exact: true })).toBeVisible()
  await page.clock.pauseAt(new Date('2026-10-19T00:01:00Z'))
  const rail = page.getByRole('toolbar')
  const git = rail.getByRole('button', { name: /Git/ })
  await git.dispatchEvent('click')
  await page.clock.runFor(32)
  await rail.locator('[data-rail-tool=files]').dispatchEvent('click')
  await page.clock.runFor(400)
  expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().active)).toBe('files')
  await page.evaluate(() => (window as any).builtinExtensionFixture.collapse())
  await page.clock.runFor(400)
  await git.dispatchEvent('click')
  await page.clock.runFor(32)
  await page.evaluate(() => (window as any).builtinExtensionFixture.open('sessions'))
  await page.clock.runFor(200)
  await expect(page.locator('#right-tool-panel-sessions')).toBeVisible()
  await git.dispatchEvent('click')
  await page.clock.runFor(64)
  await git.dispatchEvent('click')
  await page.clock.runFor(48)
  await expect(git).toHaveAttribute('aria-pressed', 'true')
  expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().toolActivations)).toEqual(['sessions', 'git'])
})

test('rail supports native keyboard activation and reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/tool-palette.html')
  const git = page.getByRole('toolbar').getByRole('button', { name: /Git/ })
  await git.focus()
  await page.keyboard.press('Enter')
  await expect(git).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByTestId('right-tool-rail-indicator')).toHaveCSS('transition-duration', '0s')
  await page.keyboard.press('Space')
  await expect(page.locator('[id^="right-tool-panel-"]:visible')).toHaveCount(0)
})
