import { test, expect } from '@playwright/test'

for (const engine of ['codex', 'opencode']) test(`${engine} edits a historical message in place and preserves the bottom draft`, async ({ page }) => {
  await page.goto(`/codex-conversation.html?initialView=conversation&engine=${engine}`)
  await page.evaluate(() => (window as any).codexFixture.editPreview())
  const draft = page.getByRole('combobox')
  await draft.fill('My next question')
  const original = page.getByText('Original question', { exact: true })
  await original.hover()
  await page.getByRole('button', { name: 'Edit message', exact: true }).nth(1).click()
  const editor = page.getByRole('textbox', { name: 'Edit message text', exact: true })
  await expect(editor).toBeFocused()
  await expect(editor).toHaveValue('Original question')
  await expect(page.getByRole('button', { name: 'Terminal', exact: true })).toBeDisabled()
  await expect(draft).toHaveText('My next question')
  await editor.fill('Revised question')
  await editor.press('Enter')
  await expect(editor).toHaveValue('Revised question\n')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual([])
  await page.evaluate(() => (window as any).codexFixture.holdSend())
  await editor.press('Control+Enter')
  await expect(page.getByRole('button', { name: 'Resending…', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeDisabled()
  await editor.press('Control+Enter')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual(['Revised question\n'])
  await page.evaluate(() => (window as any).codexFixture.releaseSend())
  await expect(editor).toHaveCount(0)
  await expect(page.getByText('Earlier question', { exact: true })).toBeVisible()
  await expect(page.getByText('Revised question', { exact: true })).toBeVisible()
  await expect(original).toHaveCount(0)
  await expect(page.getByText('Later question', { exact: true })).toHaveCount(0)
  await expect(draft).toHaveText('My next question')
})

test('failed edits keep their text and original position, including after native history was replaced', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  await page.evaluate(() => (window as any).codexFixture.editPreview())
  await page.getByText('Original question', { exact: true }).hover()
  await page.getByRole('button', { name: 'Edit message', exact: true }).nth(1).click()
  const editor = page.getByRole('textbox', { name: 'Edit message text' })
  await editor.fill('Keep my changes')
  await page.evaluate(() => (window as any).codexFixture.holdSend())
  await page.getByRole('button', { name: 'Save and resend', exact: true }).click()
  await page.evaluate(() => (window as any).codexFixture.releaseSend(true))
  await expect(editor).toHaveValue('Keep my changes')
  await expect(page.getByText('Later question', { exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('Fixture send failed')
  await page.evaluate(() => (window as any).codexFixture.editFailure())
  await page.getByRole('button', { name: 'Save and resend', exact: true }).click()
  await expect(editor).toHaveValue('Keep my changes')
  await expect(page.getByRole('alert')).toContainText('could not be confirmed')
  await expect(page.getByRole('button', { name: 'Save and resend', exact: true })).toBeDisabled()
  await expect(page.getByText('Earlier question', { exact: true })).toBeVisible()
  await expect(page.getByText('Later question', { exact: true })).toHaveCount(0)
})

