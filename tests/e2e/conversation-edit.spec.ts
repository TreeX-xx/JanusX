for (const theme of ['dark', 'light', 'narrow']) test(`inline edit design ${theme}`, async ({ page }) => {
  await page.setViewportSize({ width: theme === 'narrow' ? 440 : 1100, height: 820 })
  await page.goto(`/codex-conversation.html?initialView=conversation&theme=${theme}`)
  await page.evaluate(async () => { await (window as any).codexFixture.changeLanguage('zh-CN'); (window as any).codexFixture.designPreview() })
  await page.getByRole('button', { name: '重新编辑', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '编辑消息内容' })).toBeFocused()
  const editor = page.getByRole('form', { name: '重新编辑', exact: true })
  await expect(editor.getByRole('button', { name: '保存并重新发送' })).toBeVisible()
  expect(await editor.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: `artifacts/conversation-design/inline-edit-${theme}.png` })
})
