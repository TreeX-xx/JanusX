import { expect, test } from '@playwright/test'
import { nativeEditingKeys } from '../helpers/native-editing-keys'

for (const theme of ['dark', 'planche', 'white']) test(`attachment errors use the shared dismissible chat card in ${theme}`, async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 740 })
  await page.goto(`/codex-conversation.html?initialView=conversation&theme=${theme}`)
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  await input.fill('Keep my draft')
  await page.evaluate(() => {
    window.electron.file.importConversationAttachment = async () => { throw new Error('File no longer available') }
  })
  const dropUnavailable = () => input.evaluate(element => {
    const data = new DataTransfer()
    data.items.add(new File([], 'unavailable.txt'))
    element.dispatchEvent(new DragEvent('drop', { dataTransfer: data, bubbles: true, cancelable: true }))
  })
  await dropUnavailable()
  const card = page.locator('[data-chat-error-card]')
  await expect(card.getByRole('alert')).toHaveText('Could not add unavailable.txt.')
  expect(await card.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: `artifacts/conversation-errors/attachment-${theme}.png` })
  await card.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(card).toHaveCount(0)
  await expect(input).toBeFocused()
  await expect(input).toHaveText('Keep my draft')
  await dropUnavailable()
  await expect(card).toBeVisible()
  // A successful internal reference also clears the previous attachment error.
  await input.evaluate(element => {
    const data = new DataTransfer()
    data.setData('application/x-janusx-workspace-file', JSON.stringify({ type: 'directory', name: 'src', path: 'src', workspacePath: 'C:/fixture' }))
    element.dispatchEvent(new DragEvent('drop', { dataTransfer: data, bubbles: true, cancelable: true }))
  })
  await expect(card).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Remove src', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual([])
})

test('large images and more than eight files stay in the authored text and can be sent', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  await input.fill('Compare ')
  await page.evaluate(() => {
    const fixture = window as unknown as { previewReads: number }
    fixture.previewReads = 0
    window.electron.file.readBinary = async () => { fixture.previewReads++; return { error: 'Unexpected thumbnail read' } }
  })
  await page.locator('input[type=file]').setInputFiles([
    { name: 'large.png', mimeType: 'image/png', buffer: Buffer.alloc(11 * 1024 * 1024) },
    ...Array.from({ length: 9 }, (_, index) => ({ name: `notes-${index}.txt`, mimeType: 'text/plain', buffer: Buffer.alloc(0) })),
  ])
  await expect(input.locator('[data-reference-id]')).toHaveCount(10)
  await expect(input.getByRole('button', { name: 'Open file: large.png' })).toBeEnabled()
  expect(await page.evaluate(() => (window as any).previewReads)).toBe(0)
  await input.press(nativeEditingKeys.end)
  await input.pressSequentially('in this order')
  await input.press('Enter')
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.calls.sends.length)).toBe(1)
  const command = await page.evaluate(() => (window as any).codexFixture.calls.commands.find((item: any) => item.type === 'send'))
  expect(command.text).toMatch(/^Compare image: "C:\/attachments\/large\.png" .*file: "C:\/attachments\/notes-8\.txt" in this order$/)
  expect(command.imagePaths).toEqual([])
})

test('repeated references to one SVG stay independent and preview without a native image upload', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  await page.evaluate(() => {
    const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="2" height="1"><path d="M0 0h2v1H0z"/></svg>'
    window.electron.file.readBinary = async () => ({ base64: btoa(svg), mimeType: 'image/svg+xml', size: svg.length })
  })
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  const attach = () => page.locator('input[type=file]').setInputFiles({ name: 'logo.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('fixture') })
  await input.fill('Compare ')
  await attach()
  const chips = input.locator('[data-reference-id]')
  await expect(chips).toHaveCount(1)
  await input.pressSequentially('then revisit ')
  await attach()
  await expect(chips).toHaveCount(2)
  expect(await chips.nth(0).getAttribute('data-reference-id')).not.toBe(await chips.nth(1).getAttribute('data-reference-id'))
  const preview = input.getByRole('button', { name: 'Preview image: logo.svg' }).last()
  await expect(preview).toBeEnabled()
  await preview.click()
  await expect(page.getByRole('dialog', { name: 'Preview image: logo.svg' }).locator('img')).toBeVisible()
  await page.getByRole('button', { name: 'Close image preview' }).click()
  await input.press('Enter')
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.calls.sends.length)).toBe(1)
  const command = await page.evaluate(() => (window as any).codexFixture.calls.commands.find((item: any) => item.type === 'send'))
  expect(command.text.trimEnd()).toBe('Compare image: "C:/attachments/logo.svg" then revisit image: "C:/attachments/logo.svg"')
  expect(command.imagePaths).toEqual([])
})

test('context references survive remount, support keyboard @ navigation and send native images', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  await input.fill('Inspect @src')
  await expect(page.getByRole('button', { name: 'src/', exact: true })).toBeVisible()
  await input.press('Enter')
  await expect(page.getByRole('button', { name: 'app.ts', exact: true })).toBeVisible()
  await input.press('Enter')
  await expect(input).toContainText('Inspect app.ts')
  await expect(page.getByRole('button', { name: 'Remove app.ts' })).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({ name: 'screen.png', mimeType: 'image/png', buffer: Buffer.from([137, 80, 78, 71]) })
  await expect(page.getByRole('button', { name: 'Remove screen.png' })).toBeVisible()
  await page.getByRole('button', { name: 'Remount', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Remove screen.png' })).toBeVisible()
  await input.press('Enter')
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.calls.sends.length)).toBe(1)
  const command = await page.evaluate(() => (window as any).codexFixture.calls.commands.find((item: any) => item.type === 'send'))
  expect(command.text).toContain('C:/fixture/src/app.ts')
  expect(command.imagePaths).toEqual(['C:/attachments/screen.png'])
  await expect(page.getByRole('button', { name: 'Remove screen.png' })).toHaveCount(0)
})

test('OpenCode holds messages for a required answer, allows removal and resumes while active', async ({ page }) => {
  await page.goto('/codex-conversation.html?engine=opencode&initialView=conversation')
  const input = page.getByRole('combobox', { name: 'Message OpenCode' })
  await input.fill('First'); await input.press('Enter')
  await expect(page.getByRole('button', { name: 'Stop response' })).toBeVisible()
  await page.evaluate(() => (window as any).codexFixture.questions('text'))
  const form = page.getByRole('form', { name: 'Your response is needed' })
  await expect(form).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Delivery mode' })).toHaveCount(0)
  await input.fill('Next task'); await input.press('Enter')
  await expect(page.locator('[data-outgoing-message][data-delivery="queued"]')).toHaveCount(1)
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual(['First'])
  await page.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(page.locator('[data-outgoing-message]')).toHaveCount(0)
  await input.fill('Follow-up task'); await input.press('Enter')
  await expect(page.locator('[data-outgoing-message][data-delivery="queued"]')).toHaveCount(1)
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual(['First'])
  await form.getByRole('textbox', { name: 'Answer: Type something' }).fill('Continue')
  await form.getByRole('button', { name: 'Submit answer', exact: true }).click()
  await expect(form).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual(['First', 'Follow-up task'])
  await expect(page.getByRole('button', { name: 'Stop response' })).toBeVisible()
  const command = await page.evaluate(() => (window as any).codexFixture.calls.commands.filter((item: any) => item.type === 'send').at(-1))
  expect(command.delivery).toBeUndefined()
  expect(command.expectedTurnId).toBeUndefined()
  await page.setViewportSize({ width: 390, height: 720 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `${process.env.JANUS_CONTEXT_TEST_ARTIFACTS ?? 'artifacts'}/conversation-p0-narrow.png` })
})

test('diff feedback adds historical context to the existing draft without sending', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  await input.waitFor()
  await page.evaluate(() => (window as any).codexFixture.designPreview())
  await input.fill('Keep my draft')
  await page.locator('[data-turn-files]').click()
  await expect(page.getByRole('button', { name: 'Review current changes in Git' })).toHaveCount(0)
  await page.evaluate(() => (window as any).codexFixture.reviewProject('C:/fixture'))
  await page.getByRole('button', { name: 'Review current changes in Git' }).click()
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.reviewTool())).toMatch(/git/)
  await page.evaluate(() => (window as any).codexFixture.reviewProject('C:/different-checkout'))
  await expect(page.getByRole('button', { name: 'Review current changes in Git' })).toHaveCount(0)
  await page.locator('[data-turn-files-panel] summary').click()
  await page.getByRole('button', { name: 'Comment on patch row 1' }).focus()
  await page.getByRole('button', { name: 'Comment on patch row 1' }).press('Enter')
  await expect(input).toContainText('Keep my draft')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual([])
  await expect(page.getByRole('button', { name: 'Remove opencode-conversation.ts' })).toBeVisible()
  await input.press('Enter')
  const text = await page.evaluate(() => (window as any).codexFixture.calls.sends[0])
  expect(text).toContain('Keep my draft')
  expect(text).toContain('historical diff')
  expect(text).toContain('this.updateSettings(session.data.model)')
  await page.setViewportSize({ width: 390, height: 720 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
