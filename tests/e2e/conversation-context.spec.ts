import { expect, test } from '@playwright/test'

test('context references survive remount, support keyboard @ navigation and send native images', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  await input.fill('Inspect @src')
  await expect(page.getByRole('button', { name: 'src/', exact: true })).toBeVisible()
  await input.press('Enter')
  await expect(page.getByRole('button', { name: 'app.ts', exact: true })).toBeVisible()
  await input.press('Enter')
  await expect(input).toContainText('Inspect app.ts')
  await expect(page.getByRole('button', { name: 'Remove app.ts' })).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({ name: 'screen.png', mimeType: 'image/png', buffer: Buffer.from([137, 80, 78, 71]) })
  await expect(page.getByRole('button', { name: 'Remove screen.png' })).toBeVisible()
  await page.getByRole('button', { name: 'Remount', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Remove screen.png' })).toBeVisible()
  await input.press('Enter')
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.calls.sends.length)).toBe(1)
  const command = await page.evaluate(() => (window as any).codexFixture.calls.commands.find((item: any) => item.type === 'send'))
  expect(command.text).toContain('C:/fixture/src/app.ts')
  expect(command.imagePaths).toEqual(['C:/attachments/screen.png'])
  await expect(page.getByRole('button', { name: 'Remove screen.png' })).toHaveCount(0)
})

test('OpenCode queues without a mode selector and allows removing a waiting message', async ({ page }) => {
  await page.goto('/codex-conversation.html?engine=opencode&initialView=conversation')
  const input = page.getByRole('combobox', { name: 'Message OpenCode' })
  await input.fill('First'); await input.press('Enter')
  await expect(page.getByRole('combobox', { name: 'Delivery mode' })).toHaveCount(0)
  await input.fill('Next task'); await input.press('Enter')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual(['First'])
  await page.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(page.locator('[data-outgoing-message]')).toHaveCount(0)
  await input.fill('Follow-up task'); await input.press('Enter')
  await page.evaluate(() => (window as any).codexFixture.finish())
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual(['First', 'Follow-up task'])
  const command = await page.evaluate(() => (window as any).codexFixture.calls.commands.filter((item: any) => item.type === 'send').at(-1))
  expect(command.delivery).toBe('queue')
  expect(command.expectedTurnId).toBeUndefined()
  await page.setViewportSize({ width: 390, height: 720 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/conversation-p0-narrow.png' })
})

test('diff feedback adds historical context to the existing draft without sending', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  await input.waitFor()
  await page.evaluate(() => (window as any).codexFixture.designPreview())
  await input.fill('Keep my draft')
  await page.locator('[data-turn-files] > summary').click()
  await expect(page.getByRole('button', { name: 'Review current changes in Git' })).toHaveCount(0)
  await page.evaluate(() => (window as any).codexFixture.reviewProject('C:/fixture'))
  await page.getByRole('button', { name: 'Review current changes in Git' }).click()
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.reviewTool())).toMatch(/git/)
  await page.evaluate(() => (window as any).codexFixture.reviewProject('C:/different-checkout'))
  await expect(page.getByRole('button', { name: 'Review current changes in Git' })).toHaveCount(0)
  await page.locator('[data-turn-files] details > summary').click()
  await page.getByRole('button', { name: 'Comment on patch row 1' }).focus()
  await page.getByRole('button', { name: 'Comment on patch row 1' }).press('Enter')
  await expect(input).toContainText('Keep my draft')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual([])
  await expect(page.getByRole('button', { name: 'Remove opencode-conversation.ts' })).toBeVisible()
  await input.press('Enter')
  const text = await page.evaluate(() => (window as any).codexFixture.calls.sends[0])
  expect(text).toContain('Keep my draft')
  expect(text).toContain('historical diff')
  expect(text).toContain('this.updateSettings(session.data.model)')
  await page.setViewportSize({ width: 390, height: 720 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
