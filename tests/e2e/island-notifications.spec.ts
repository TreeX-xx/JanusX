import { expect, test, type Page } from '@playwright/test'

type FixtureWindow = Window & { automationChatFixture: {
  notify(id: string, task?: string, message?: string, state?: 'succeeded' | 'failed'): void
  collapse(): void
} }
async function notify(page: Page, id: string, task = 'phone', message = 'Check your phone', state: 'succeeded' | 'failed' = 'succeeded') {
  await page.evaluate(({ id, task, message, state }) => (window as FixtureWindow).automationChatFixture.notify(id, task, message, state), { id, task, message, state })
}
const shell = (page: Page) => page.locator('.janus-island-shell')
const reader = (page: Page) => page.locator('.janus-notification-center')

test.beforeEach(async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/automation-chat.html')
  await expect(page.getByTestId('open-island')).toBeVisible()
})

test('arrival grows vertically, reads on one click, and closing keeps the record and task action', async ({ page }) => {
  test.setTimeout(40_000) // Includes a cold fixture load and both normal-motion morphs.
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.getByTestId('open-island').focus()
  await notify(page, 'run-1')
  await expect(shell(page)).toHaveAttribute('data-speaking', 'true')
  await expect(page.locator('.janus-speak-body')).toHaveText('Check your phone')
  await expect.poll(async () => (await shell(page).boundingBox())!.height).toBeGreaterThanOrEqual(88)
  await expect(page.getByTestId('open-island')).toBeFocused()
  await page.screenshot({ path: test.info().outputPath('notification-preview.png') })
  await page.getByRole('button', { name: 'Read notification: Phone reminder', exact: true }).click()
  await expect(reader(page)).toBeVisible()
  await expect(shell(page)).toHaveAttribute('data-stage', 'collapsed')
  await expect(reader(page).getByText('0 unread')).toBeVisible()
  await expect(reader(page).locator('.janus-notif-body')).toHaveText('Check your phone')
  await page.keyboard.press('Escape')
  await expect(reader(page)).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Notifications, 0 unread', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Notifications, 0 unread', exact: true }).press('Enter')
  await expect(reader(page).locator('.janus-notif-row')).toHaveCount(1)
  await reader(page).getByRole('button', { name: 'View task', exact: true }).hover()
  await expect(page.locator('.janus-island')).toHaveCSS('animation-name', 'none')
  await reader(page).getByRole('button', { name: 'View task', exact: true }).click()
  await expect(page.locator('.automation-report')).toContainText('Check your phone')
  await expect(reader(page)).toHaveCount(0)
})

test('hover and keyboard focus pause the preview; timeout only collapses', async ({ page }) => {
  await page.clock.install()
  await notify(page, 'run-1')
  await page.locator('.janus-speak-body').hover()
  await page.clock.runFor(7000)
  await expect(shell(page)).toHaveAttribute('data-speaking', 'true')
  await page.getByRole('button', { name: 'Read', exact: true }).focus()
  await page.mouse.move(20, 500)
  await page.clock.runFor(7000)
  await expect(shell(page)).toHaveAttribute('data-speaking', 'true')
  await page.getByTestId('open-island').focus()
  await page.clock.runFor(6100)
  await expect(shell(page)).toHaveAttribute('data-speaking', 'false')
  expect((await shell(page).boundingBox())!.height).toBeLessThan(32)
  await expect(page.locator('.janus-history-count')).toHaveCount(0)
  await expect(page.locator('.janus-unread-indicator')).toHaveCount(0)
  await expect(page.locator('.janus-unread-rim')).toHaveCount(0)
  for (const theme of ['dark', 'planche']) {
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
    await page.screenshot({ path: test.info().outputPath(`capsule-unread-${theme}.png`) })
  }
  await page.getByRole('button', { name: 'Notifications, 1 unread', exact: true }).click()
  await expect(reader(page).locator('.janus-notif-row')).toHaveCount(1)
})

test('deleting the whole card removes its notification and rejects late completion events', async ({ page }) => {
  await notify(page, 'delete-run')
  await page.getByRole('button', { name: 'Read', exact: true }).click()
  await notify(page, 'keep-run', 'Keep reminder', 'Keep this notification')
  await reader(page).getByRole('button', { name: 'View task', exact: true }).click()
  const card = page.locator('.automation-card').filter({ has: page.getByRole('button', { name: 'Phone reminder', exact: true }) })
  await expect(card.locator('.automation-report')).toContainText('Check your phone')
  await page.locator('.automation-panel').getByRole('button', { name: 'Open Island', exact: true }).click()
  await expect(shell(page)).toHaveAttribute('data-stage', 'expanded')
  await card.getByRole('button', { name: 'Delete card', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(shell(page)).toHaveAttribute('data-stage', 'expanded')
  await card.getByRole('button', { name: 'Delete card', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete card', exact: true }).click()
  await expect(card).toHaveCount(0)
  await expect(shell(page)).toHaveAttribute('data-stage', 'expanded')
  await expect(page.locator('.automation-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Notifications, 1 unread', exact: true }).click()
  await expect(reader(page).locator('.janus-notif-row')).toHaveCount(1)
  await expect(reader(page).locator('.janus-notif-body')).toHaveText('Keep this notification')
  await notify(page, 'late-run')
  await expect(reader(page).locator('.janus-notif-row')).toHaveCount(1)
  await expect(reader(page)).not.toContainText('Phone reminder')
})

test('repeat reminders group by task and arrivals do not change the selected record or reading position', async ({ page }) => {
  await notify(page, 'run-1')
  await page.getByRole('button', { name: 'Read', exact: true }).click()
  await notify(page, 'run-2', 'phone', 'Check your phone again')
  await expect(reader(page).locator('.janus-notif-row')).toHaveCount(1)
  await expect(reader(page).getByText('2 times')).toBeVisible()
  await expect(reader(page).getByText('1 unread')).toBeVisible()
  await expect(reader(page).locator('.janus-notif-body')).toHaveText('Check your phone again')
  await page.evaluate(() => { for (let i = 0; i < 12; i++) (window as FixtureWindow).automationChatFixture.notify('extra-' + i, 'task-' + i, 'A separate reminder') })
  const list = reader(page).locator('.janus-notif-list')
  await list.evaluate(el => { el.scrollTop = 150 })
  const before = await list.evaluate(el => el.scrollTop)
  await notify(page, 'run-other', 'other', 'Another task')
  await expect(reader(page).locator('[data-selected="true"]')).toContainText('Phone reminder')
  expect(await list.evaluate(el => el.scrollTop)).toBe(before)
  await expect(shell(page)).toHaveAttribute('data-speaking', 'false')
  await page.mouse.click(20, 500)
  await expect(reader(page)).toHaveCount(0)
  await notify(page, 'run-3', 'phone', 'Check again now')
  await expect(page.locator('.janus-speak-body')).toHaveText('Check again now')
  await expect(page.locator('.janus-speak-kicker')).toContainText('×3')
})

test('Chat keeps input and focus on arrival, and uses the same reader and explicit clearing', async ({ page }) => {
  await notify(page, 'run-1')
  await page.getByTestId('open-island').click()
  const input = page.locator('.janus-chat-input')
  await input.fill('Keep this draft')
  await notify(page, 'failed-run', 'failed-task', 'Task needs attention', 'failed')
  await expect(input).toBeFocused()
  await expect(input).toHaveValue('Keep this draft')
  await expect(shell(page)).toHaveAttribute('data-stage', 'expanded')
  await expect(shell(page)).toHaveAttribute('data-speaking', 'false')
  await expect(page.locator('.janus-notify-banner')).toHaveCount(0)
  for (const theme of ['dark', 'planche']) {
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
    await shell(page).screenshot({ path: test.info().outputPath(`notification-entry-${theme}.png`) })
  }
  await page.getByRole('button', { name: 'Notifications, 2 unread', exact: true }).click()
  await expect(reader(page).locator('.janus-notif-row')).toHaveCount(2)
  await expect(reader(page).getByText('1 unread')).toBeVisible()
  for (const theme of ['dark', 'planche']) {
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
    await shell(page).screenshot({ path: test.info().outputPath(`notification-tray-${theme}.png`) })
  }
  await reader(page).getByRole('button', { name: 'Clear read', exact: true }).click()
  await expect(reader(page).locator('.janus-notif-row')).toHaveCount(1)
  await expect(reader(page)).toContainText('Phone reminder')
  await page.keyboard.press('Escape')
  await expect(reader(page)).toHaveCount(0)
  await expect(shell(page)).toHaveAttribute('data-stage', 'expanded')
  await page.evaluate(() => (window as FixtureWindow).automationChatFixture.collapse())
  await expect(shell(page)).toHaveAttribute('data-speaking', 'false')
  await page.getByRole('button', { name: 'Notifications, 1 unread', exact: true }).click()
  await expect(reader(page).locator('.janus-notif-row')).toHaveCount(1)
  await reader(page).getByRole('button', { name: 'Clear all', exact: true }).click()
  await expect(reader(page).getByText('No notice history')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.janus-unread-rim')).toHaveCount(0)
})

test('long notification content stays readable in a compact viewport in both themes', async ({ page }) => {
  await page.setViewportSize({ width: 600, height: 640 })
  const message = 'Check your phone.\n' + 'Complete reminder details with a long reference abcdefghijklmnopqrstuvwxyz0123456789. '.repeat(15)
  await notify(page, 'long', 'phone', message)
  for (const theme of ['dark', 'planche']) {
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
    await page.screenshot({ path: test.info().outputPath('preview-' + theme + '.png') })
  }
  await page.getByRole('button', { name: 'Read', exact: true }).click()
  await expect(reader(page).locator('.janus-notif-body')).toHaveText(message)
  const box = (await shell(page).boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(600)
  expect(box.y + box.height).toBeLessThanOrEqual(640)
  expect(await reader(page).locator('.janus-notif-list').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await reader(page).getByRole('button', { name: 'View task', exact: true }).scrollIntoViewIfNeeded()
  await expect(reader(page).getByRole('button', { name: 'View task', exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('reader-compact.png') })
  for (const theme of ['dark', 'planche']) {
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
    await reader(page).locator('.janus-notif-list').evaluate(el => { el.scrollTop = 0 })
    await page.screenshot({ path: test.info().outputPath(`reader-compact-${theme}.png`) })
  }
  await page.keyboard.press('Escape')
  await page.getByTestId('open-island').click()
  await page.getByRole('button', { name: 'Notifications, 0 unread', exact: true }).click()
  const tray = page.locator('.janus-notify-tray')
  const trayBox = (await tray.boundingBox())!
  expect(trayBox.x).toBeGreaterThanOrEqual(0)
  expect(trayBox.x + trayBox.width).toBeLessThanOrEqual(600)
  expect(trayBox.y + trayBox.height).toBeLessThanOrEqual(640)
  await reader(page).getByRole('button', { name: 'View task', exact: true }).scrollIntoViewIfNeeded()
  await expect(reader(page).getByRole('button', { name: 'View task', exact: true })).toBeVisible()
})
