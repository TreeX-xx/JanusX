import { expect, test } from '@playwright/test'

const pageErrors: string[] = []
test.beforeEach(({ page }) => { pageErrors.length = 0; page.on('pageerror', (error) => pageErrors.push(error.message)) })
test.afterEach(() => expect(pageErrors).toEqual([]))

test('island and project panel entries stay independent across panel remounts', async ({ page }) => {
  await page.goto('/project.html')
  await page.addStyleTag({ content: '.fixture-layout { display:grid; grid-template-columns:repeat(2,minmax(0,1fr)); gap:16px; padding:16px; } .fixture-layout > section { display:flex; flex-direction:column; min-width:0; height:650px; overflow:auto; } .fixture-layout .janus-chat { width:100%; height:100%; } @media(max-width:600px) { .fixture-layout { grid-template-columns:minmax(0,1fr); } }' })
  const main = page.getByTestId('main-chat')
  const blueprint = page.getByTestId('project-panel')
  await expect(blueprint.locator('.janus-chat')).toBeVisible()
  const id = await page.getByTestId('controller').getAttribute('data-id')
  const panelId = await page.getByTestId('project-controller').getAttribute('data-id')
  expect(panelId).toBeTruthy()
  expect(panelId).not.toBe(id!)
  await main.locator('textarea').fill('Inspect this task')
  await main.locator('textarea').press('Enter')
  await expect(main).toContainText('Project reply in progress')
  await page.evaluate(() => (window as any).projectFixture.finishStream())
  await expect(main).toContainText('Inspect this task')
  await expect(blueprint).not.toContainText('Inspect this task')
  await blueprint.locator('.janus-chat textarea').fill('Keep the scope narrow')
  await blueprint.locator('.janus-chat textarea').press('Enter')
  await expect(blueprint).toContainText('Project reply in progress')
  await expect(main).not.toContainText('Keep the scope narrow')
  const streams = await page.evaluate(() => (window as any).projectFixture.streams)
  expect(streams).toHaveLength(2)
  expect(new Set(streams.map((item: { conversationId: string }) => item.conversationId)).size).toBe(2)
  await page.getByRole('button', { name: 'Choose model B', exact: true }).click()
  await expect(page.getByTestId('controller')).toHaveAttribute('data-model', 'model-b')
  await page.getByRole('button', { name: 'Ask question', exact: true }).click()
  await expect(main).not.toContainText('Which scope?')
  await expect(blueprint).toContainText('Which scope?')
  await blueprint.getByRole('radio', { name: /Selected/ }).check()
  await blueprint.getByRole('button', { name: 'Answer', exact: true }).click()
  await expect(page.getByTestId('project-controller')).toHaveAttribute('data-id', panelId!)
  await expect(blueprint).not.toContainText('Which scope?')
  expect(await page.evaluate(() => (window as any).projectFixture.answers)).toBe(1)
  await page.getByRole('button', { name: 'Ask approval', exact: true }).click()
  await expect(main.locator('.janus-runtime-approval')).toHaveCount(0)
  await expect(blueprint.locator('.janus-runtime-approval')).toBeVisible()
  await blueprint.locator('.janus-runtime-approval-approve').click()
  await expect(blueprint.locator('.janus-runtime-approval')).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).projectFixture.approvals)).toBe(1)
  await page.getByRole('button', { name: 'Toggle project panel', exact: true }).click()
  expect(await page.evaluate(() => (window as any).projectFixture.aborts)).toBe(0)
  await page.getByRole('button', { name: 'Toggle project panel', exact: true }).click()
  await expect(blueprint).toContainText('Keep the scope narrow')
  await expect(page.getByTestId('controller')).toHaveAttribute('data-id', id!)
  await expect(page.getByTestId('project-controller')).toHaveAttribute('data-id', panelId!)
  await page.getByRole('button', { name: 'New personal chat', exact: true }).click()
  await expect(page.getByTestId('controller')).not.toHaveAttribute('data-id', id!)
  await expect(page.getByTestId('project-controller')).toHaveAttribute('data-id', panelId!)
  await expect(page.getByTestId('project-controller')).toHaveAttribute('data-streaming', 'true')
  await expect(main).not.toContainText('Inspect this task')
  await expect(blueprint).toContainText('Keep the scope narrow')
  await page.getByRole('button', { name: 'Return to main chat', exact: true }).click()
  await expect(page.getByTestId('controller')).toHaveAttribute('data-id', id!)
  await expect(main).toContainText('Inspect this task')
  await page.screenshot({ path: test.info().outputPath('shared-project-desktop.png'), fullPage: true, animations: 'disabled' })
  await blueprint.locator('.janus-chat-stop').click()
  await expect(page.getByTestId('project-controller')).toHaveAttribute('data-streaming', 'false')
  expect(await page.evaluate(() => (window as any).projectFixture.aborts)).toBe(1)
  // Island home conversation carries no workspace resources; the panel hides its chips.
  await expect(main.locator('.janus-resource-chip')).toHaveCount(0)
  await expect(blueprint.locator('.janus-chat-sidebar')).toHaveCount(0)
  await expect(blueprint.locator('.bp-maintenance-context')).toHaveCount(0)
  await expect(blueprint.locator('.bp-maintenance-controls')).toHaveCount(0)
  await expect(blueprint.getByRole('button', { name: 'Organize Notes', exact: true })).toHaveCount(0)
  await expect(blueprint.locator('.bp-maintenance-policy-hint')).toHaveCount(0)
  await page.reload()
  await expect(page.getByTestId('controller')).toHaveAttribute('data-id', id!)
  await expect(page.getByTestId('main-chat')).toContainText('Inspect this task')
  await expect(page.getByTestId('main-chat').locator('.janus-resource-chip')).toHaveCount(0)
  // The panel session is ephemeral: restart drops its history and rebinds fresh.
  await expect(page.getByTestId('project-panel')).not.toContainText('Keep the scope narrow')
  await expect(page.getByTestId('project-controller')).not.toHaveAttribute('data-id', panelId!)
  await expect(page.getByTestId('project-panel').locator('.janus-chat textarea')).toBeVisible()
})

test('workspace switching while the panel is unmounted clears only the panel and cancels its old stream', async ({ page }) => {
  await page.goto('/project.html?switch-workspace')
  const main = page.getByTestId('main-chat')
  const panel = page.getByTestId('project-panel')
  await main.locator('textarea').fill('Keep island history')
  await main.locator('textarea').press('Enter')
  await expect(main).toContainText('Project reply in progress')
  await page.evaluate(() => (window as any).projectFixture.finishStream())
  await panel.locator('textarea').fill('Old workspace discussion')
  await panel.locator('textarea').press('Enter')
  await expect(panel).toContainText('Project reply in progress')
  await page.getByRole('button', { name: 'Toggle project panel', exact: true }).click()
  expect(await page.evaluate(() => (window as any).projectFixture.aborts)).toBe(0)
  await page.evaluate(() => (window as any).projectFixture.switchWorkspace('ws-b'))
  await expect.poll(() => page.evaluate(() => (window as any).projectFixture.aborts)).toBe(1)
  await page.evaluate(() => (window as any).projectFixture.finishStream())
  await page.getByRole('button', { name: 'Toggle project panel', exact: true }).click()
  await expect(panel.locator('textarea')).toBeVisible()
  await expect(panel).not.toContainText('Old workspace discussion')
  await expect(panel).not.toContainText('Project reply in progress')
  await expect(main).toContainText('Keep island history')
  await panel.locator('textarea').fill('New workspace discussion')
  await panel.locator('textarea').press('Enter')
  await expect(panel).toContainText('Project reply in progress')
  const request = await page.evaluate(() => (window as any).projectFixture.streams.at(-1))
  expect(request.workspaceResources.map((item: any) => item.workspaceId)).toEqual(['ws-b'])
  expect(request.messages.some((message: any) => message.content.includes('Old workspace'))).toBe(false)
  expect(request.maintenanceTaskId).toBeUndefined()
})

