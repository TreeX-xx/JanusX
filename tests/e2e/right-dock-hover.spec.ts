import { expect, test } from '@playwright/test'

test('an open hover card follows rail targets without another dwell delay', async ({ page }) => {
  await page.goto('/tool-palette.html')
  const shell = page.getByTestId('right-tool-panel-shell')
  await page.locator('#right-tool-rail-files').click()
  await expect(shell).toHaveAttribute('data-visible', 'false')
  await page.mouse.move(400, 40)
  // Fully release the original docked panel before testing the initial dwell.
  await page.waitForTimeout(350)
  await page.clock.install()
  await page.clock.pauseAt(new Date())

  await page.locator('#right-tool-rail-sessions').hover()
  await page.clock.runFor(200)
  await expect(shell).toHaveAttribute('aria-hidden', 'true')
  await page.clock.runFor(40)
  await expect(page.locator('#right-tool-panel-sessions')).toBeVisible()

  // Each target gets only two frames, well below the initial 220ms dwell.
  for (const id of ['git', 'files', 'sessions', 'git', 'sessions']) {
    await page.locator(`#right-tool-rail-${id}`).hover()
    await page.clock.runFor(32)
    await expect(page.locator(`#right-tool-panel-${id}`)).toBeVisible()
    await expect(page.locator(`#right-tool-rail-${id}`)).toHaveAttribute('data-visual-active', 'true')
    await expect(shell).toHaveAttribute('data-visible', 'true')
  }
  // A pending leave cannot dismiss the next target, even during exit.
  await page.mouse.move(400, 40)
  await page.clock.runFor(200)
  await expect(shell).toHaveAttribute('aria-hidden', 'true')
  await page.locator('#right-tool-rail-git').hover()
  await page.clock.runFor(32)
  await expect(page.locator('#right-tool-panel-git')).toBeVisible()
  await page.clock.runFor(240)
  await expect(shell).toHaveAttribute('data-visible', 'true')
  expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().active)).toBe('files')
})

for (const theme of ['planche', 'dark']) {
  test(`collapsed tools preview interactively and pin without remounting in ${theme}`, async ({ page }) => {
    await page.goto(`/tool-palette.html?theme=${theme}`)
    const shell = page.getByTestId('right-tool-panel-shell')
    const files = page.locator('#right-tool-rail-files')
    const sessions = page.locator('#right-tool-rail-sessions')
    await expect(page.getByRole('tablist')).toHaveCount(0)
    await expect(page.locator('[aria-controls="right-tool-panel"]')).toHaveCount(0)
    await files.click()
    await expect(shell).toHaveAttribute('data-visible', 'false')
    const before = await page.evaluate(() => (window as any).builtinExtensionFixture.state())
    await sessions.hover()
    await expect(shell).toHaveAttribute('data-preview', 'true')
    const panel = page.locator('#right-tool-panel-sessions')
    const input = panel.getByRole('textbox')
    await input.fill('终端管理')
    await expect(panel.locator('[data-session-id]')).toHaveCount(1)
    expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().active)).toBe(before.active)
    expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().open)).toEqual(before.open)
    await expect.poll(() => shell.locator('..').evaluate(el => Math.round(el.getBoundingClientRect().width))).toBe(48)
    await expect(shell).toHaveCSS('border-radius', '10px')
    await expect(shell).toHaveCSS('opacity', '1')
    const center = page.locator('#preview-underlay').locator('..')
    const previewCenterWidth = (await center.boundingBox())!.width
    await page.screenshot({ path: test.info().outputPath(`hover-card-${theme}.png`) })
    await sessions.click()
    await expect(shell).toHaveAttribute('data-transient', 'false')
    // The same visible surface morphs while the center yields space.
    const during = await shell.evaluate(async el => {
      await new Promise(resolve => setTimeout(resolve, 60))
      const style = getComputedStyle(el)
      return { radius: parseFloat(style.borderTopLeftRadius), opacity: Number(style.opacity) }
    })
    expect(during.radius).toBeGreaterThan(0)
    expect(during.radius).toBeLessThan(10)
    expect(during.opacity).toBe(1)
    await expect(shell).toHaveCSS('border-radius', '0px')
    await expect(shell).toHaveCSS('right', '48px')
    await expect(shell).toHaveCSS('top', '0px')
    await expect(shell).toHaveCSS('box-shadow', 'none')
    await expect.poll(async () => Math.round((await shell.locator('..').boundingBox())!.width)).toBe(408)
    expect((await center.boundingBox())!.width).toBeCloseTo(previewCenterWidth - 360, 0)
    await expect(input).toHaveValue('终端管理')
    await expect(page.locator('#right-tool-panel-sessions')).toHaveCount(1)
    await sessions.click()
    await expect(shell).toHaveAttribute('data-visible', 'false')
    await page.mouse.move(400, 40)
    await files.hover()
    await expect(shell).toHaveAttribute('data-preview', 'true')
    await page.locator('#right-tool-panel-files').getByText('README.md', { exact: true }).hover()
    await page.waitForTimeout(250)
    await expect(shell).toHaveAttribute('data-visible', 'true')
    await page.mouse.move(400, 40)
    await expect(shell).toHaveAttribute('data-visible', 'false')
  })
}

test('hovering between closed tools reuses the mounted subtree instead of remounting', async ({ page }) => {
  await page.goto('/tool-palette.html')
  const shell = page.getByTestId('right-tool-panel-shell')
  const files = page.locator('#right-tool-rail-files')
  const sessions = page.locator('#right-tool-rail-sessions')
  const git = page.locator('#right-tool-rail-git')
  await files.click()
  await expect(shell).toHaveAttribute('data-visible', 'false')
  // Only a tool outside openToolIds is mounted temporarily while previewed, so
  // close both targets first to exercise the hover-switch path.
  await page.evaluate(() => {
    (window as any).builtinExtensionFixture.close('sessions')
    ;(window as any).builtinExtensionFixture.close('git')
  })

  // Fill local component state in each preview, then switch away and back.
  await sessions.hover()
  await expect(shell).toHaveAttribute('data-preview', 'true')
  const sessionSearch = page.locator('#right-tool-panel-sessions').getByRole('textbox')
  await sessionSearch.fill('悬浮切换探针')
  await git.hover()
  await expect(shell).toHaveAttribute('data-preview', 'true')
  await expect(page.locator('#right-tool-panel-git')).toBeVisible()
  const commitInput = page.locator('#right-tool-panel-git').getByRole('textbox').first()
  await commitInput.fill('git 侧探针')

  await sessions.hover()
  await expect(shell).toHaveAttribute('data-preview', 'true')
  await expect(sessionSearch).toHaveValue('悬浮切换探针')

  await git.hover()
  await expect(shell).toHaveAttribute('data-preview', 'true')
  await expect(commitInput).toHaveValue('git 侧探针')
  // Previewing must not reopen the closed tools.
  expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().open)).toEqual(['files'])
})

test('preview cancels on Escape, outside click, workspace switch and disabled contribution', async ({ page }) => {
  await page.goto('/tool-palette.html')
  const shell = page.getByTestId('right-tool-panel-shell')
  const files = page.locator('#right-tool-rail-files')
  const sessions = page.locator('#right-tool-rail-sessions')
  await files.click()
  await expect(shell).toHaveAttribute('data-visible', 'false')
  await page.mouse.move(400, 40)
  await sessions.hover()
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  await expect(shell).toHaveAttribute('data-visible', 'false')
  await sessions.focus()
  await expect(shell).toHaveAttribute('data-preview', 'true')
  await page.keyboard.press('ArrowLeft')
  await expect(page.locator('#right-tool-panel-sessions').getByRole('textbox')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(shell).toHaveAttribute('data-visible', 'false')
  await page.mouse.move(400, 40)
  await sessions.hover()
  await expect(shell).toHaveAttribute('data-preview', 'true')
  await page.mouse.click(400, 40)
  await expect(shell).toHaveAttribute('data-visible', 'false')
  await sessions.hover()
  await expect(shell).toHaveAttribute('data-preview', 'true')
  await page.evaluate(() => (window as any).builtinExtensionFixture.selectProject('other'))
  await expect(shell).toHaveAttribute('data-visible', 'false')
  await page.mouse.move(400, 40)
  await sessions.hover()
  await expect(shell).toHaveAttribute('data-preview', 'true')
  await page.evaluate(() => (window as any).builtinExtensionFixture.disable('sessions'))
  await expect(shell).toHaveAttribute('data-visible', 'false')
  await expect(sessions).toHaveCount(0)
})

test('narrow layout uses a bounded click overlay and hover does not open closed tools', async ({ page }) => {
  await page.setViewportSize({ width: 740, height: 600 })
  await page.goto('/tool-palette.html?panel=520')
  const shell = page.getByTestId('right-tool-panel-shell')
  await page.evaluate(() => (window as any).builtinExtensionFixture.close('sessions'))
  const sessions = page.locator('#right-tool-rail-sessions')
  await sessions.hover()
  await expect(shell).toHaveAttribute('data-preview', 'true')
  expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().open)).not.toContain('sessions')
  await expect(shell).toHaveAttribute('data-visible', 'true')
  await expect(shell).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
  const bounds = (await shell.boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(8)
  expect(bounds.x + bounds.width).toBeLessThan(740 - 48)
  await page.keyboard.press('Escape')
  await sessions.click()
  await expect(shell).toHaveAttribute('data-visible', 'true')
  await sessions.click()
  await expect(shell).toHaveAttribute('data-visible', 'false')
})
