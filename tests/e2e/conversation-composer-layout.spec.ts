import { test, expect } from '@playwright/test'

test('context control stays on the bottom toolbar and its popup does not move the draft', async ({ page }) => {
  await page.setViewportSize({ width: 380, height: 720 })
  await page.goto('/codex-conversation.html?initialView=conversation')
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  const add = page.getByRole('button', { name: 'Add context', exact: true })
  const model = page.getByRole('button', { name: 'Choose model' })
  await input.fill('Keep this draft')
  await input.evaluate(el => el.closest('form')!.getAnimations().forEach(animation => animation.finish()))
  const before = await input.boundingBox()
  const button = (await add.boundingBox())!
  const modelBox = (await model.boundingBox())!
  expect(button.y).toBeGreaterThan(before!.y + before!.height)
  expect(button.x).toBeLessThan(modelBox.x)
  expect(Math.abs(button.y + button.height / 2 - modelBox.y - modelBox.height / 2)).toBeLessThan(2)
  await add.click()
  const menu = page.getByRole('dialog', { name: 'Add context' })
  await expect(menu).toBeVisible()
  await expect(page.getByRole('button', { name: 'Attach files', exact: true })).toBeFocused()
  expect(await input.boundingBox()).toEqual(before)
  const menuBox = (await menu.boundingBox())!
  expect(menuBox.y + menuBox.height).toBeLessThan(button.y)
  expect(menuBox.x + menuBox.width).toBeLessThanOrEqual(380)
  await page.screenshot({ path: 'artifacts/conversation-composer/context-menu-narrow.png' })
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await expect(add).toBeFocused()
  await add.click()
  await input.click({ position: { x: before!.width - 8, y: 8 } })
  await expect(menu).toHaveCount(0)
  await expect(input).toHaveText('Keep this draft')
  await add.click()
  await page.getByRole('button', { name: 'Reference files or folders (@)', exact: true }).click()
  const search = page.getByRole('textbox', { name: 'Search files or enter a path' })
  await expect(search).toBeFocused()
  await expect(input).toHaveText('Keep this draft')
  expect(await input.boundingBox()).toEqual(before)
  await search.fill('src')
  await search.press('Enter')
  await expect(page.getByRole('button', { name: 'app.ts', exact: true })).toBeVisible()
  await search.press('Enter')
  await expect(page.getByRole('button', { name: 'Remove app.ts' })).toBeVisible()
  await expect(input).toBeFocused()
  await expect(input).toContainText('Keep this draft')
  await page.getByRole('button', { name: 'Remove app.ts' }).click()
  await add.click()
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Attach files', exact: true }).click()
  await (await chooser).setFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('Context') })
  await expect(page.getByRole('button', { name: 'Remove notes.txt' })).toBeVisible()
  await expect(menu).toHaveCount(0)
  await expect(input.getByRole('button', { name: 'Remove notes.txt' })).toBeVisible()
  await page.getByRole('button', { name: 'Remove notes.txt' }).click()
  await expect(input).toHaveText('Keep this draft')
})

for (const engine of ['claude', 'opencode']) test(`${engine} accepts more input while working and queues it immediately`, async ({ page }) => {
  await page.goto(`/codex-conversation.html?engine=${engine}&initialView=conversation`)
  const input = page.getByRole('combobox', { name: engine === 'claude' ? 'Message Claude' : 'Message OpenCode' })
  await input.fill('First task'); await input.press('Enter')
  await expect(page.getByRole('button', { name: 'Stop response' })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Delivery mode' })).toHaveCount(0)
  await input.fill('Next task'); await input.press('Enter')
  await expect(input).toHaveText('')
  await expect(page.getByText('Next task', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual(['First task'])
  await page.evaluate(() => (window as any).codexFixture.finish())
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual(['First task', 'Next task'])
})

 test('model and context pickers share their anchor and preserve the draft', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  const input = page.getByRole('combobox', { name: 'Message Codex' })
  await input.fill('Keep this draft')
  await page.getByRole('button', { name: 'Choose model' }).click()
  const search = page.getByRole('combobox', { name: 'Search options' })
  await expect(search).toBeVisible()
  const modelPanel = page.locator('[data-panel="model"]')
  const modelBox = (await modelPanel.boundingBox())!
  await page.screenshot({ path: 'artifacts/conversation-composer/model-picker.png' })
  await page.getByRole('button', { name: 'Add context', exact: true }).click()
  await expect(modelPanel).toHaveCount(0)
  const contextBox = (await page.getByRole('dialog', { name: 'Add context' }).boundingBox())!
  expect(contextBox.x).toBe(modelBox.x)
  expect(Math.abs(contextBox.y + contextBox.height - modelBox.y - modelBox.height)).toBeLessThan(1)
  await page.getByRole('button', { name: 'Reference files or folders (@)', exact: true }).click()
  await page.getByRole('textbox', { name: 'Search files or enter a path' }).press('Escape')
  await expect(page.getByRole('button', { name: 'Attach files', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(input).toHaveText('Keep this draft')
  await input.fill('/model ')
  await expect(search).toBeVisible()
  await search.fill('gpt')
  await expect(input).toHaveText('/model gpt')
  await search.press('Escape')
  await expect(input).toHaveText('/')
  await expect(input).toBeFocused()
 })
