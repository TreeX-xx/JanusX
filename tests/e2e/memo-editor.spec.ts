import { expect, test } from '@playwright/test'

// Headless Chromium otherwise suppresses the native scrollbar we exercise.
test.use({ launchOptions: { ignoreDefaultArgs: ['--hide-scrollbars'] } })

test.beforeEach(async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/memo.html?island=1')
  await page.getByRole('button', { name: 'Open memo on the right' }).click()
  await page.getByRole('button', { name: 'A', exact: true }).click()
  await page.evaluate(async () => {
    const memo = (window as any).memoFixture.memos[0]
    await window.electron.memo!.edit(memo.id, { expectedRevision: memo.revision, operations: [{ op: 'addNode', title: 'First' }, { op: 'addNode', title: 'Second' }] })
  })
})

test('inline record composer supports multiline, empty validation, cancel and node draft restoration', async ({ page }) => {
  await page.getByRole('button', { name: 'Add point' }).click()
  const composer = page.getByRole('dialog', { name: 'Add point' })
  await composer.getByRole('button', { name: 'OK', exact: true }).click()
  await expect(composer.getByRole('status')).toBeVisible()
  await composer.getByRole('textbox').fill('First line\nSecond line')
  await page.getByRole('tab', { name: 'First', exact: true }).press('ArrowRight')
  await expect(composer).toHaveCount(0)
  await page.getByRole('tab', { name: 'Second', exact: true }).press('ArrowLeft')
  await expect(composer.getByRole('textbox')).toHaveValue('First line\nSecond line')
  await composer.getByRole('textbox').press('Control+Enter')
  await expect(composer).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'Point text' })).toHaveValue('First line\nSecond line')
  await page.getByRole('button', { name: 'Add point' }).click()
  await composer.getByRole('textbox').fill('Discard this')
  await composer.press('Escape')
  await expect(page.locator('.memo-panel')).toBeVisible()
  expect(await page.evaluate(() => (window as any).memoFixture.memos[0].nodes[0].points.length)).toBe(1)
})

test('failed record creation preserves text and retries only on confirmation', async ({ page }) => {
  await page.getByRole('button', { name: 'Add point' }).click()
  const composer = page.getByRole('dialog')
  await composer.getByRole('textbox').fill('Retain my idea')
  await page.evaluate(() => {
    const edit = window.electron.memo!.edit
    window.electron.memo!.edit = async () => { window.electron.memo!.edit = edit; throw new Error('Fixture write failed') }
  })
  await composer.getByRole('button', { name: 'OK', exact: true }).click()
  await expect(composer.getByRole('status')).toBeVisible()
  await expect(composer.getByRole('textbox')).toHaveValue('Retain my idea')
  expect(await page.evaluate(() => (window as any).memoFixture.memos[0].nodes[0].points.length)).toBe(0)
  await composer.getByRole('textbox').press('Control+Enter')
  await expect(composer).toHaveCount(0)
  await expect(page.locator('.memo-point')).toHaveCount(1)
})

test('document fields save explicitly, revert with Escape and allow clearing the optional label', async ({ page }) => {
  const title = page.getByRole('textbox', { name: 'Node title', exact: true })
  await title.fill('Draft title')
  await title.press('Escape')
  await expect(title).toHaveValue('First')
  await expect(page.locator('.memo-panel')).toBeVisible()
  await title.fill('Saved title')
  await title.press('Enter')
  await expect(title).toBeFocused()
  await expect(page.locator('.memo-field[data-state="saved"]')).toContainText('Saved')
  const label = page.getByRole('textbox', { name: 'Version or time label' })
  await label.fill('v1')
  await label.press('Enter')
  await expect(page.locator('.memo-star-label')).toHaveText('v1')
  await label.fill('')
  await label.press('Enter')
  await expect(page.locator('.memo-star-label')).toHaveCount(0)
})

test('record menus dismiss outside and never cover star actions', async ({ page }) => {
  await page.getByRole('button', { name: 'Add point' }).click()
  await page.getByRole('dialog').getByRole('textbox').fill('A visible record')
  await page.getByRole('dialog').getByRole('textbox').press('Control+Enter')
  await page.locator('.memo-point').hover()
  await page.getByLabel('Record actions', { exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Move to node' })).toBeVisible()
  await page.getByLabel('Star actions', { exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Move to node' })).toBeHidden()
  await page.getByRole('button', { name: 'Delete star', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('all records (1)')
})

for (const theme of ['dark', 'planche']) test(`record scrolling and themed node picker preserve the island and move records (${theme})`, async ({ page }) => {
  await page.evaluate(async theme => {
    document.documentElement.dataset.theme = theme
    const memo = (window as any).memoFixture.memos[0]
    await window.electron.memo!.edit(memo.id, { expectedRevision: memo.revision,
      operations: Array.from({ length: 20 }, (_, index) => ({ op: 'addPoint' as const, nodeId: memo.nodes[0].id, text: `Record ${index + 1}: release planning and interface refinements` })) })
  }, theme)
  const scroll = page.locator('.memo-scroll')
  const width = await scroll.evaluate(element => element.clientWidth)
  await scroll.hover()
  await page.mouse.wheel(0, 350)
  await expect.poll(() => scroll.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  expect(await scroll.evaluate(element => element.clientWidth)).toBe(width)
  await scroll.evaluate(element => { element.scrollTop = 0 })
  const track = await scroll.boundingBox()
  await page.mouse.move(track!.x + track!.width - 5, track!.y + 10)
  await page.mouse.down()
  await page.mouse.move(track!.x + track!.width - 5, track!.y + 70, { steps: 5 })
  await page.mouse.up()
  await expect.poll(() => scroll.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  await scroll.evaluate(element => { element.scrollTop = 0 })
  const first = page.locator('.memo-point').first()
  await first.hover()
  await first.getByLabel('Record actions', { exact: true }).click()
  const picker = page.getByRole('combobox', { name: 'Move to node' })
  await picker.click()
  const list = page.getByRole('listbox', { name: 'Move to node' })
  await expect(list).toBeVisible()
  await expect(list.getByRole('option', { name: 'First', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.screenshot({ path: `artifacts/memo-analysis/controls-${theme}.png` })
  await picker.press('Escape')
  await expect(list).toHaveCount(0)
  await expect(page.locator('.memo-panel')).toBeVisible()
  await picker.press('ArrowDown')
  await picker.press('End')
  await picker.press('Enter')
  await expect(first.getByRole('textbox', { name: 'Point text' })).toHaveValue('Record 2: release planning and interface refinements')
  await first.hover()
  await first.getByLabel('Record actions', { exact: true }).click()
  await picker.click()
  await list.getByRole('option', { name: 'Second', exact: true }).click()
  await expect(page.locator('.memo-panel')).toBeVisible()
  await expect(page.locator('.memo-point')).toHaveCount(18)
  const moved = await page.evaluate(() => (window as any).memoFixture.memos[0].nodes[1].points.map((point: any) => point.text))
  expect(moved).toEqual(['Record 1: release planning and interface refinements', 'Record 2: release planning and interface refinements'])
})

