test('keeps cached content during refresh and failure, with no redundant connection check', async ({ page }) => {
  await page.goto('/repository.html?overview')
  await expect(page.getByRole('heading', { name: 'Alpha', exact: true })).toBeVisible()
  await page.evaluate(() => { (window as any).repositoryFixture.holdReads = true })
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await expect(page.getByText('Updating…', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Alpha', exact: true })).toBeVisible()
  await page.evaluate(() => { (window as any).repositoryFixture.failRead = true; (window as any).repositoryFixture.releaseReads() })
  await expect(page.getByRole('alert')).toContainText('Network unavailable')
  await expect(page.getByRole('heading', { name: 'Alpha', exact: true })).toBeVisible()
  expect(await page.evaluate(() => (window as any).repositoryFixture.counts.connection)).toBe(1)
  await page.evaluate(() => { (window as any).repositoryFixture.failRead = false })
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
})

test('deduplicates in-flight tab reads and clears private content on authorization failure', async ({ page }) => {
  await page.goto('/repository.html?overview')
  await expect(page.getByRole('heading', { name: 'Alpha', exact: true })).toBeVisible()
  await page.evaluate(() => { (window as any).repositoryFixture.holdReads = true })
  await page.getByRole('tab', { name: 'Issues', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).repositoryFixture.counts.browse)).toBe(1)
  await page.getByRole('tab', { name: 'Overview', exact: true }).click()
  await page.getByRole('tab', { name: 'Issues', exact: true }).click()
  await page.evaluate(() => (window as any).repositoryFixture.releaseReads())
  await expect(page.getByText('Alpha issue 1', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => (window as any).repositoryFixture.counts.browse)).toBe(1)
  await page.evaluate(() => { const f = (window as any).repositoryFixture; f.failDetail = true; f.authorized = false })
  await page.getByText('Alpha issue 1', { exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign in to your repository', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Alpha issue 1' })).toHaveCount(0)
  await page.evaluate(() => { const f = (window as any).repositoryFixture; f.failDetail = false; f.authorized = true; f.resetSession() })
  await page.getByRole('tab', { name: 'Overview', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Alpha', exact: true })).toBeVisible()
  expect(await page.evaluate(() => (window as any).repositoryFixture.counts.overview)).toBe(2)
})

