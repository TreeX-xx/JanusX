import { expect, test } from '@playwright/test'

test('workspace entry exposes inheritance, search, source paths and explicit MCP testing', async ({ page }) => {
  await page.goto('/settings.html?tab=integrations&workspace')
  await expect(page.getByRole('heading', { name: '技能与 MCP', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /project-conventions/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /code-review.*继承/ })).toBeVisible()
  await page.getByRole('textbox', { name: '搜索名称、描述或路径' }).fill('frontend')
  await expect(page.getByRole('button', { name: /frontend-design/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /code-review/ })).toHaveCount(0)
  await page.getByRole('tab', { name: /MCP/ }).click()
  await page.getByRole('button', { name: /filesystem/ }).click()
  expect(await page.locator('html').getAttribute('data-integration-probes')).toBeNull()
  await expect(page.getByText('已配置', { exact: true }).last()).toBeVisible()
  await page.getByRole('button', { name: '检测连接', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('本次检测通过')
  await expect(page.locator('html')).toHaveAttribute('data-integration-probes', '1')
  await page.getByRole('button', { name: '打开所在位置' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-integration-reveal', /filesystem/)
  await page.screenshot({ path: 'artifacts/local-integrations/mcp-dark.png' })
})

test('add skill targets the project source and edit updates only the selected entry', async ({ page }) => {
  await page.goto('/settings.html?tab=integrations&workspace&en')
  await page.getByRole('button', { name: 'Add skill', exact: true }).click()
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('new-skill')
  const editor = page.getByRole('textbox', { name: 'SKILL.md content', exact: true })
  await expect(editor).toHaveValue(/name: new-skill/)
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Saved.')
  const saved = JSON.parse((await page.locator('html').getAttribute('data-integration-save'))!)
  expect(saved.query).toEqual({ client: 'codex', scope: 'workspace', workspaceId: 'demo' })
  expect(saved.sourceId).toContain(':workspace:skill')
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await editor.fill('---\nname: new-skill\ndescription: Updated\n---\n\nKeep it focused.')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText(/Keep it focused\./)).toBeVisible()
  expect(JSON.parse((await page.locator('html').getAttribute('data-integration-save'))!).entryId).toContain('new-skill')
})

test('a stale-file rejection retains the draft', async ({ page }) => {
  await page.goto('/settings.html?tab=integrations&changed')
  await page.getByRole('button', { name: /code-review/ }).click()
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  const editor = page.getByRole('textbox', { name: 'SKILL.md 内容', exact: true })
  await editor.fill('---\nname: code-review\ndescription: Draft\n---\nKeep this unsaved draft.')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('文件已被外部修改')
  await expect(editor).toHaveValue(/Keep this unsaved draft/)
  await expect(page.getByRole('button', { name: '保存', exact: true })).toBeEnabled()
})

test('client switching shows read-only plugin skills and links to plugin management', async ({ page }) => {
  await page.goto('/settings.html?tab=integrations&en')
  await page.getByRole('button', { name: 'Client', exact: true }).click()
  await page.getByRole('option', { name: 'Janus', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Add skill', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: /Blueprint review/ }).click()
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Manage plugins', exact: true }).last().click()
  await expect(page.locator('[data-tab="plugins"]')).toHaveAttribute('aria-current', 'page')
})

for (const theme of ['dark', 'white', 'planche']) {
  test(`local resources fit ${theme} in wide and narrow settings`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 980 })
    await page.goto(`/settings.html?tab=integrations&workspace&theme=${theme}`)
    await expect(page.getByRole('button', { name: /project-conventions/ })).toBeVisible()
    await page.screenshot({ path: `artifacts/local-integrations/skills-${theme}.png`, animations: 'disabled' })
    await page.getByRole('button', { name: /code-review/ }).click()
    await expect(page.getByRole('heading', { name: 'code-review', exact: true })).toBeVisible()
    expect(await page.locator('main').evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await page.screenshot({ path: `artifacts/local-integrations/detail-${theme}.png`, animations: 'disabled' })
    await page.setViewportSize({ width: 640, height: 800 })
    expect(await page.locator('main').evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await page.getByRole('button', { name: '编辑', exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'SKILL.md 内容' })).toBeVisible()
    expect(await page.locator('main').evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await page.getByRole('button', { name: '保存', exact: true }).scrollIntoViewIfNeeded()
    await expect(page.getByRole('button', { name: '保存', exact: true })).toBeInViewport()
    await page.screenshot({ path: `artifacts/local-integrations/narrow-${theme}.png`, animations: 'disabled' })
  })
}
