import { expect, test } from '@playwright/test'

for (const runtime of ['wsl', 'ssh']) {
  test(`${runtime}: missing CLI offers installation in the terminal, then opens automatically`, async ({ page }) => {
    await page.goto(`/terminal-startup.html?remote=${runtime}&theme=dark`)
    await page.getByRole('button', { name: 'New Codex' }).click()
    const panel = page.getByRole('region', { name: 'Install Agent' })
    await expect(panel).toContainText(runtime === 'wsl' ? 'WSL · Ubuntu' : 'SSH · dev-server')
    expect(await page.evaluate(() => (window as any).startupFixture.pending())).toBe(false)
    await page.screenshot({ path: `artifacts/remote-agent-${runtime}.png` })
    await panel.getByRole('button', { name: 'Install and open' }).click()
    await expect(panel.getByRole('button', { name: 'Install and open' })).toBeDisabled()
    await expect(panel.getByRole('status')).toContainText('Preparing and installing')
    await page.evaluate(() => { (window as any).remoteCliFixture.state = 'complete' })
    await expect(panel).toHaveCount(0)
    await expect.poll(() => page.evaluate(() => (window as any).startupFixture.pending())).toBe(true)
    expect(await page.evaluate(() => (window as any).remoteCliFixture.installs)).toBe(1)
    await page.evaluate(() => { (window as any).startupFixture.ready(); (window as any).startupFixture.output('Codex ready') })
    await expect(page.getByRole('status')).toHaveCount(0)
  })
}

test('installed CLI opens directly and an install failure remains recoverable', async ({ page }) => {
  await page.goto('/terminal-startup.html?remote=wsl')
  await page.evaluate(() => { (window as any).remoteCliFixture.installed = true })
  await page.getByRole('button', { name: 'New Codex' }).click()
  await expect.poll(() => page.evaluate(() => (window as any).startupFixture.pending())).toBe(true)
  await expect(page.getByRole('region', { name: 'Install Agent' })).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).remoteCliFixture.installs)).toBe(0)
  await page.reload()
  await page.getByRole('button', { name: 'New Codex' }).click()
  const panel = page.getByRole('region', { name: 'Install Agent' })
  await page.evaluate(() => { (window as any).remoteCliFixture.fail = true })
  await panel.getByRole('button', { name: 'Install and open' }).click()
  await expect(panel.getByRole('alert')).toContainText('Target download failed')
  await expect(panel.getByRole('button', { name: 'Install and open' })).toBeEnabled()
  await panel.getByRole('button', { name: 'Open Linux terminal' }).click()
  await expect(panel).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => (window as any).startupFixture.pending())).toBe(true)
})

test('closing an installation panel cannot launch a terminal when the remote job finishes', async ({ page }) => {
  await page.goto('/terminal-startup.html?remote=ssh')
  await page.getByRole('button', { name: 'New Codex' }).click()
  const panel = page.getByRole('region', { name: 'Install Agent' })
  await panel.getByRole('button', { name: 'Install and open' }).click()
  await expect(panel.getByRole('status')).toBeVisible()
  await panel.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.evaluate(() => { (window as any).remoteCliFixture.state = 'complete' })
  await expect(panel).toHaveCount(0)
  await page.waitForTimeout(1100)
  expect(await page.evaluate(() => (window as any).startupFixture.pending())).toBe(false)
})

test('a failed remote installer retains its output and can be retried in place', async ({ page }) => {
  await page.goto('/terminal-startup.html?remote=ssh')
  await page.getByRole('button', { name: 'New Codex' }).click()
  const panel = page.getByRole('region', { name: 'Install Agent' })
  await panel.getByRole('button', { name: 'Install and open' }).click()
  await page.evaluate(() => { (window as any).remoteCliFixture.state = 'failed' })
  await expect(panel.getByRole('alert')).toBeVisible()
  await panel.getByText('Installation details', { exact: true }).click()
  await expect(panel.locator('pre')).toContainText('Installing Agent package')
  await page.evaluate(() => { (window as any).remoteCliFixture.state = 'running' })
  await panel.getByRole('button', { name: 'Install and open' }).click()
  await expect(panel.getByRole('status')).toBeVisible()
  await page.evaluate(() => { (window as any).remoteCliFixture.state = 'complete' })
  await expect(panel).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => (window as any).startupFixture.pending())).toBe(true)
  expect(await page.evaluate(() => (window as any).remoteCliFixture.installs)).toBe(2)
})

test('a status query failure does not claim that the remote installation failed', async ({ page }) => {
  await page.goto('/terminal-startup.html?remote=wsl')
  await page.getByRole('button', { name: 'New Codex' }).click()
  const panel = page.getByRole('region', { name: 'Install Agent' })
  await page.evaluate(() => { (window as any).remoteCliFixture.statusFail = true })
  await panel.getByRole('button', { name: 'Install and open' }).click()
  await expect(panel.getByRole('alert')).toContainText('Unable to read installation status')
  await expect(panel.getByRole('alert')).toContainText('may still be running')
  expect(await page.evaluate(() => (window as any).remoteCliFixture.installs)).toBe(1)
  await page.evaluate(() => { (window as any).remoteCliFixture.statusFail = false })
  await panel.getByRole('button', { name: 'Install and open' }).click()
  await expect(panel.getByRole('status')).toBeVisible()
  await page.evaluate(() => { (window as any).remoteCliFixture.state = 'complete' })
  await expect(panel).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => (window as any).startupFixture.pending())).toBe(true)
})
