import { expect, test, type Page } from '@playwright/test'

async function settings(page: Page) {
  await page.getByRole('button', { name: '设置', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '通用', exact: true })
  await expect(dialog).toBeVisible()
  return dialog
}

for (const theme of ['dark', 'planche']) test(`mobile remote is enabled in settings and stays at the bottom of the rail in ${theme}`, async ({ page }) => {
  test.setTimeout(60000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`/onboarding.html?existing&remote&theme=${theme}`)
  await expect(page.locator('[data-onboarding="shell"]')).toBeVisible()
  const main = page.locator('[class*="workbenchGrid"] > main')
  const trigger = page.locator('[data-mobile-remote]')
  await expect(trigger).toHaveCount(0)
  const original = (await main.boundingBox())!
  expect(original.y + original.height).toBe(720)
  const modal = await settings(page)
  const toggle = modal.getByRole('switch', { name: '启用手机远程' })
  await expect(toggle).not.toBeChecked()
  await page.evaluate(() => { (window as any).remoteFixture.failSave = true })
  await toggle.click()
  await expect(modal.getByRole('alert').filter({ hasText: '手机远程' })).toContainText('保存失败')
  await expect(toggle).not.toBeChecked()
  await expect(trigger).toHaveCount(0)
  await page.evaluate(() => { (window as any).remoteFixture.failSave = false })
  await toggle.click()
  await expect(toggle).toBeChecked()
  await page.screenshot({ path: test.info().outputPath(`settings-${theme}.png`) })
  await modal.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(modal).toHaveCount(0)
  await expect(trigger).toBeVisible()
  expect((await main.boundingBox())!.height).toBe(original.height)
  const rect = (await trigger.boundingBox())!
  expect(rect.y + rect.height).toBeGreaterThan(700)
  expect(rect.x).toBeGreaterThan(1230)
  expect(await page.evaluate(() => (window as any).remoteFixture.starts)).toBe(0)
  await page.reload()
  await expect(trigger).toBeVisible()
  const files = page.getByRole('button', { name: /打开文件工具/ })
  await files.click()
  await expect(files).toHaveAttribute('aria-pressed', 'true')
  expect((await trigger.boundingBox())!.y + (await trigger.boundingBox())!.height).toBeGreaterThan(700)
  await files.click()
  await expect(files).toHaveAttribute('aria-pressed', 'false')
  await trigger.click()
  const remote = page.getByRole('dialog', { name: '手机远程', exact: true })
  await expect(remote).toBeVisible()
  await expect.poll(() => page.evaluate(() => (window as any).onboardingFixture.occlusion())).toBe(1)
  await remote.getByRole('button', { name: '开启并生成二维码' }).click()
  await expect(remote.getByRole('img', { name: '手机配对二维码' })).toBeVisible()
  expect(await page.evaluate(() => (window as any).remoteFixture.status.workspaceId)).toBe('intro-project')
  await page.keyboard.press('Escape')
  await expect(remote).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect.poll(() => page.evaluate(() => (window as any).onboardingFixture.occlusion())).toBe(0)
  await page.evaluate(() => { (window as any).remoteFixture.status.pending = { id: 'phone', name: 'Test phone' } })
  await expect(trigger).toHaveAccessibleName(/手机等待批准/)
  await expect(trigger).toContainText('!')
  await trigger.click()
  await remote.getByRole('button', { name: '批准', exact: true }).click()
  await expect(trigger).toHaveAccessibleName(/1 个远程终端/)
  await page.setViewportSize({ width: 900, height: 650 })
  const panel = (await remote.boundingBox())!
  expect(panel.x).toBeGreaterThanOrEqual(8)
  expect(panel.y).toBeGreaterThanOrEqual(38)
  expect(panel.x + panel.width).toBeLessThan((await trigger.boundingBox())!.x)
  await page.screenshot({ path: test.info().outputPath(`remote-${theme}.png`) })
  await page.mouse.click(300, 50)
  await expect(remote).toHaveCount(0)
  const finalSettings = await settings(page)
  const finalToggle = finalSettings.getByRole('switch', { name: '启用手机远程' })
  await page.evaluate(() => { (window as any).remoteFixture.failSave = true })
  await finalToggle.click()
  await expect(finalSettings.getByRole('alert').filter({ hasText: '手机远程' })).toContainText('保存失败')
  await expect(finalToggle).toBeChecked()
  await expect(trigger).toBeVisible()
  await page.evaluate(() => { (window as any).remoteFixture.failSave = false })
  await finalToggle.click()
  await expect(finalToggle).not.toBeChecked()
  await expect(trigger).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).remoteFixture.disables)).toBe(1)
  await page.reload()
  await expect(page.locator('[data-onboarding="shell"]')).toBeVisible()
  await expect(trigger).toHaveCount(0)
  expect((await main.boundingBox())!.y + (await main.boundingBox())!.height).toBe(650)
  expect(errors).toEqual([])
})
