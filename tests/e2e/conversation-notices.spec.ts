import { test, expect } from '@playwright/test'

test('retry updates in place, preserves the draft and disappears on recovery without new input', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  const input = page.getByRole('combobox')
  await input.fill('Keep my draft')
  await page.evaluate(() => (window as any).codexFixture.retryStatus())
  const notice = page.locator('[data-conversation-notice=retry]')
  await expect(notice.getByRole('status')).toHaveText('Retrying connection1/5')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(notice.locator('pre')).toBeHidden()
  await notice.getByText('View details').click()
  await expect(notice.locator('pre')).toContainText('interrupted')
  await page.evaluate(() => (window as any).codexFixture.retryStatus('retry', 'Reconnecting... 2/5'))
  await expect(notice).toHaveCount(1)
  await expect(notice.getByRole('status')).toHaveText('Retrying connection2/5')
  await page.evaluate(() => (window as any).codexFixture.retryStatus('recovered'))
  await expect(notice).toHaveCount(0)
  await expect(page.getByText('Connection recovered. Review complete.')).toBeVisible()
  await expect(input).toHaveText('Keep my draft')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual([])
})

test('native retry, turn failure and connection errors have no duplicate terminal banner', async ({ page }) => {
  await page.goto('/codex-conversation.html')
  for (const stage of ['retry', 'failed']) {
    await page.evaluate(stage => (window as any).codexFixture.retryStatus(stage), stage)
    await expect(page.locator('.xterm')).toBeVisible()
    await expect(page.locator('[data-conversation-notice]:visible')).toHaveCount(0)
    await page.getByRole('button', { name: 'Conversation', exact: true }).click()
    await expect(page.locator('[data-conversation-notice]:visible')).toHaveCount(1)
    await page.getByRole('button', { name: 'Terminal', exact: true }).click()
  }
  await page.evaluate(() => (window as any).codexFixture.fail())
  await expect(page.locator('[data-conversation-notice]:visible')).toHaveCount(0)
})

test('failure remains in its own turn, outside collapsed tools, while the next turn runs', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  await page.evaluate(() => (window as any).codexFixture.retryStatus('failed', 'Retry limit reached'))
  const failure = page.locator('[data-conversation-notice=failure]')
  await expect(failure.getByRole('alert')).toHaveText('This response could not be completed')
  await failure.getByText('View details').click()
  await expect(failure.locator('pre')).toHaveText('Retry limit reached')
  await page.getByRole('combobox').fill('Continue the review')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(failure).toHaveCount(1)
  await expect(page.locator('[data-conversation-notice=retry]')).toHaveCount(0)
  await expect(page.getByText('Continue the review', { exact: true })).toBeVisible()
})

for (const theme of ['dark', 'planche', 'white']) test(`retry and failure notices fit a narrow ${theme} pane`, async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 740 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`/codex-conversation.html?initialView=conversation&theme=${theme}`)
  await page.evaluate(() => (window as any).codexFixture.changeLanguage('zh-CN'))
  await page.evaluate(() => (window as any).codexFixture.retryStatus('retry', 'Reconnecting... 1/5\n' + 'connection-detail/'.repeat(40)))
  const retry = page.locator('[data-conversation-notice=retry]')
  await expect(retry.getByRole('status')).toHaveText('正在重试连接1/5')
  await expect(retry.locator('svg')).toHaveCSS('animation-name', 'none')
  await page.screenshot({ path: `artifacts/conversation-notices/retry-${theme}.png` })
  await page.evaluate(() => (window as any).codexFixture.retryStatus('failed', '连接重试次数已用尽。\n' + 'connection-detail/'.repeat(40)))
  const failure = page.locator('[data-conversation-notice=failure]')
  await failure.getByText('查看详情', { exact: true }).click()
  expect(await failure.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `artifacts/conversation-notices/failure-${theme}.png` })
})
