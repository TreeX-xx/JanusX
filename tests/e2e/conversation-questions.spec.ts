test('asynchronous Codex questions remain actionable during work and after completion', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  const draft = page.getByRole('combobox')
  await draft.fill('Keep this draft')
  await page.evaluate(() => (window as any).codexFixture.asyncQuestions())
  const form = page.getByRole('form', { name: 'Your response is needed' })
  await expect(form.getByRole('radio', { name: 'Second', exact: true })).toBeEnabled()
  await form.getByRole('radio', { name: 'Second', exact: true }).check()
  await form.getByRole('textbox', { name: 'Answer: Notes' }).fill('中文异步回答')
  await page.evaluate(() => (window as any).codexFixture.finish())
  await expect(form).toBeVisible()
  await expect(form.getByRole('button', { name: 'Cancel request', exact: true })).toHaveCount(0)
  await form.getByRole('button', { name: 'Submit answer', exact: true }).click()
  await expect(form).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).codexFixture.calls.commands.filter((c: any) => c.type === 'answer'))).toMatchObject([{
    requestId: 'async:active-turn:ask', answer: { answers: [{ id: '0', selected: ['1'] }, { id: '1', selected: [], text: '中文异步回答' }] },
  }])
  await expect(draft).toHaveText('Keep this draft')
})

