import { test, expect } from '@playwright/test'

test('preserves multiple approval scopes and wraps them in a narrow pane', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 })
  await page.goto('/codex-conversation.html?initialView=conversation')
  await page.evaluate(() => (window as any).codexFixture.approvalChoices())
  const policy = page.getByRole('button', { name: /Always allow commands matching/ })
  await expect(policy).toBeVisible()
  const bounds = await policy.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  await page.getByRole('button', { name: 'Allow for this session', exact: true }).click()
  expect(await page.evaluate(() => (window as any).codexFixture.calls.approvals)).toEqual(['acceptForSession'])
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual([])
})

test('answers y/n, multiple choices and custom text without sending a chat message', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  const draft = page.getByRole('combobox')
  await draft.fill('Keep my next message')
  await page.evaluate(() => (window as any).codexFixture.questions())
  const form = page.getByRole('form', { name: 'Your response is needed' })
  const submit = form.getByRole('button', { name: 'Submit answer', exact: true })
  await expect(submit).toBeDisabled()
  await form.getByRole('radio', { name: 'No', exact: true }).check()
  await form.getByRole('checkbox', { name: /Unit tests/ }).check()
  await form.getByRole('checkbox', { name: /Browser tests/ }).check()
  await form.getByRole('textbox', { name: 'Answer: Checks' }).fill('Extra checks')
  await form.getByRole('textbox', { name: 'Answer: Type something' }).fill('中文 原文')
  await page.getByRole('button', { name: 'Terminal', exact: true }).click()
  await page.getByRole('button', { name: 'Conversation', exact: true }).click()
  await expect(form.getByRole('textbox', { name: 'Answer: Type something' })).toHaveValue('中文 原文')
  await expect(submit).toBeEnabled()
  await page.evaluate(() => (window as any).codexFixture.holdSend())
  await submit.click()
  await expect(form.getByRole('button', { name: 'Submitting…' })).toBeDisabled()
  expect(await page.evaluate(() => (window as any).codexFixture.calls.commands.filter((c: any) => c.type === 'answer'))).toMatchObject([{
    answer: { answers: [{ id: 'confirm', selected: ['no'] }, { id: 'checks', selected: ['unit', 'browser'], text: 'Extra checks' }, { id: 'text', selected: [], text: '中文 原文' }] },
  }])
  expect(await page.evaluate(() => (window as any).codexFixture.calls.sends)).toEqual([])
  await page.evaluate(() => (window as any).codexFixture.releaseSend())
  await expect(form).toHaveCount(0)
  await expect(draft).toHaveText('Keep my next message')
})

test('composition never submits, expired requests disappear, and cancellation is explicit', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation')
  await page.evaluate(() => (window as any).codexFixture.questions('text'))
  const input = page.getByRole('textbox', { name: 'Answer: Type something' })
  await input.fill('中文')
  await input.dispatchEvent('compositionstart')
  await input.press('Enter')
  expect(await page.evaluate(() => (window as any).codexFixture.calls.commands.filter((c: any) => c.type === 'answer'))).toEqual([])
  await input.dispatchEvent('compositionend')
  await page.evaluate(() => (window as any).codexFixture.expireQuestions())
  await expect(input).toHaveCount(0)
  await page.evaluate(() => (window as any).codexFixture.questions('text'))
  await page.getByRole('button', { name: 'Cancel request', exact: true }).click()
  expect(await page.evaluate(() => (window as any).codexFixture.calls.commands.find((c: any) => c.type === 'answer').answer)).toEqual({ cancelled: true, answers: [] })
})

for (const theme of ['dark', 'light']) test(`question controls fit a narrow ${theme} pane`, async ({ page }) => {
  await page.setViewportSize({ width: 480, height: 940 })
  await page.goto(`/codex-conversation.html?initialView=conversation&theme=${theme}`)
  await page.evaluate(() => (window as any).codexFixture.questions())
  const form = page.getByRole('form', { name: 'Your response is needed' })
  await expect(form.getByRole('radio', { name: 'Yes', exact: true })).toBeVisible()
  await page.evaluate(async () => { await Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {}))) })
  await form.getByRole('button', { name: 'Submit answer' }).scrollIntoViewIfNeeded()
  const buttons = await form.getByRole('button', { name: 'Submit answer' }).boundingBox()
  const composer = await page.getByRole('combobox').boundingBox()
  expect(buttons!.y + buttons!.height).toBeLessThan(composer!.y)
  expect(await form.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: `artifacts/conversation-interactions/questions-${theme}.png` })
})
