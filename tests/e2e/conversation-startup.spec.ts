import { test, expect } from '@playwright/test'

test('direct conversation startup retains composer and syncs model and effort when ready', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation&pendingStartup')
  const input = page.locator('[data-conversation-input]')
  const model = page.getByRole('button', { name: 'Choose model', exact: true })
  const effort = page.getByRole('button', { name: 'Choose reasoning effort', exact: true })
  await expect(page.getByText(/Starting conversation/)).toBeVisible()
  const loading = page.locator('[data-conversation-loading]')
  await expect(loading).toBeVisible()
  expect(await loading.evaluate(el => el.getAnimations({ subtree: true }).length)).toBeGreaterThan(0)
  await page.screenshot({ path: 'artifacts/codex-startup/conversation-loading.png' })
  await expect(page.getByText(/Read-only conversation/)).toHaveCount(0)
  await expect(model).toBeDisabled()
  await expect(effort).toBeDisabled()
  await input.fill('Keep startup draft')
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  await page.evaluate(() => (window as any).codexFixture.starting())
  await expect(page.getByText(/Starting conversation/)).toBeVisible()
  await expect(page.locator('.xterm')).toBeHidden()
  await expect(input).toBeFocused()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(input).toHaveText('Keep startup draft')
  await expect(effort).toBeDisabled()
  const inputBeforeReady = await input.boundingBox()
  await page.evaluate(() => (window as any).codexFixture.ready())
  await expect(page.locator('.xterm')).toBeHidden()
  await expect(input).toBeFocused()
  await expect(model).toHaveText('Fixture Fast')
  await expect(effort).toContainText('High')
  await expect(model).toBeEnabled()
  await expect(effort).toBeEnabled()
  await expect(page.getByText(/Starting conversation/)).toBeHidden()
  await expect(loading).toHaveCount(0)
  expect(Math.abs((await input.boundingBox())!.y - inputBeforeReady!.y)).toBeLessThan(2)
  await page.screenshot({ path: 'artifacts/codex-startup/conversation-ready.png' })
  await expect(input).toHaveText('Keep startup draft')
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeEnabled()
  await page.evaluate(() => (window as any).codexFixture.readOnly())
  await expect(page.getByText(/Read-only conversation/)).toBeVisible()
  await expect(input).toHaveCount(0)
})

test('conversation startup respects reduced motion and yields to errors', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 720 })
  await page.goto('/codex-conversation.html?initialView=conversation&pendingStartup&theme=light')
  const loading = page.locator('[data-conversation-loading]')
  await expect(loading).toBeVisible()
  expect(await loading.evaluate(el => el.getAnimations({ subtree: true }).length)).toBe(0)
  await page.screenshot({ path: 'artifacts/codex-startup/conversation-loading-light.png' })
  await page.evaluate(() => (window as any).codexFixture.starting())
  await page.evaluate(() => (window as any).codexFixture.fail())
  await expect(loading).toHaveCount(0)
  await expect(page.getByRole('alert')).toContainText('Fixture connection lost')
})

test('startup trust stays inline, can pause and resume, and preserves the draft without exposing the terminal', async ({ page }) => {
  await page.goto('/codex-conversation.html?initialView=conversation&pendingStartup')
  const input = page.locator('[data-conversation-input]')
  await input.fill('Keep my draft')
  await page.evaluate(() => (window as any).codexFixture.setup('trust'))
  const dialog = page.getByRole('region', { name: 'Trust this folder?' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText('C:/fixture/project')).toBeVisible()
  await expect(page.locator('.xterm')).toBeHidden()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await input.fill('Keep my draft')
  await expect(input).toBeFocused()
  await expect(page.locator('[data-agent-session] [data-conversation-startup]')).toHaveCount(1)
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Conversation startup is paused.')).toBeVisible()
  await expect(input).toHaveText('Keep my draft')
  await page.getByRole('button', { name: 'Continue setup' }).click()
  await expect(dialog).toBeVisible()
  await expect(dialog).toHaveCSS('opacity', '1')
  await page.screenshot({ path: 'artifacts/codex-startup/trust-inline.png' })
  await dialog.getByRole('button', { name: 'Trust and continue' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(input).toBeFocused()
  await expect(input).toHaveText('Keep my draft')
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeEnabled()
  expect(await page.evaluate(() => (window as any).codexFixture.startupCalls)).toEqual(['cancel', 'resume', 'trust'])
  expect(await page.evaluate(() => (window as any).codexFixture.calls.input)).not.toContain('\r')
})

test('login dialog opens the browser on request and disappears after account confirmation', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 720 })
  await page.goto('/codex-conversation.html?initialView=conversation&pendingStartup&theme=light')
  await page.evaluate(() => (window as any).codexFixture.setup('login'))
  const dialog = page.getByRole('region', { name: 'Sign in to Codex' })
  await expect(dialog).toBeVisible()
  await dialog.locator('summary').filter({ hasText: 'Or use an OpenAI API key' }).click()
  await expect(dialog.getByLabel('Or use an OpenAI API key')).toHaveAttribute('type', 'password')
  await dialog.getByRole('button', { name: 'Continue with ChatGPT' }).click()
  await expect(dialog.getByText(/Complete sign-in in your browser/)).toBeVisible()
  await expect.poll(() => page.evaluate(() => (window as any).codexFixture.calls.opens)).toEqual(['https://auth.openai.com/authorize?state=fixture'])
  await dialog.getByRole('button', { name: 'Open sign-in page' }).click()
  expect(await page.evaluate(() => (window as any).codexFixture.calls.opens)).toHaveLength(2)
  await expect(page.locator('.xterm')).toBeHidden()
  await page.screenshot({ path: 'artifacts/codex-startup/login-inline-mobile.png' })
  await page.evaluate(() => (window as any).codexFixture.ready())
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('[data-conversation-input]')).toBeFocused()
})

