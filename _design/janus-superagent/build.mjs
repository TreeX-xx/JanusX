import { readFile, writeFile } from 'node:fs/promises';
const read = name => readFile(new URL(name, import.meta.url), 'utf8');
const logo = (await readFile(new URL('../../resources/icon.png', import.meta.url))).toString('base64');
let html = await read('index.template.html');
const css = await read('demo.css');
html = html.replace('/* DEMO_CSS */', () => '/* Generated by build.mjs. Edit demo.css. */\n' + css);
const script = await read('demo.js');
html = html.replace('/* DEMO_JS */', () => script);
html = html.replaceAll('__LOGO__', 'data:image/png;base64,' + logo);
await writeFile(new URL('index.html', import.meta.url), html);
console.log('Built offline index.html');
